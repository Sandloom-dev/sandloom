def test_the_report_counts_and_names_what_a_change_moves() -> None:
    register = _register(
        edges=[
            _row("R1", current_status="fixed"),
            _row("R2", current_status="retained", target="retained", reason="protocol"),
            _row("R3", kind="documentation", current_status="retained", reason="doc"),
        ]
    )
    base = {r.id: r for r in _register(edges=[_row("R1"), _row("R2"), _row("R0")]).rows}
    text = ke.report(register, ke.Outcome(), base)
    for line in (
        "by kind: documentation: 1, runtime: 2",
        "by class: b: 3",
        "by type: naming: 3",
        "by scope: runtime: 3",
        "by current status: fixed: 1, retained: 2",
        "by target: fixed: 2, retained: 1",
        "added by this change: R3",
        "fixed by this change: R1",
        "retained by this change: R2, R3",
        "removed by this change: R0",
    ):
        assert line in text, text


def test_the_script_exits_non_zero_on_a_problem(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    assert ke.main([]) == 0
    monkeypatch.setattr(
        ke, "load_register", lambda: _register(edges=[_row(current_status="fixed")])
    )
    monkeypatch.setattr(
        ke,
        "scan",
        lambda *a, **k: [ke.Finding("sandloom/core/x.py", 1, "crm", "module-name")],
    )
    assert ke.main(["--report"]) == 1
    assert "problems:" in capsys.readouterr().out
