"""The kernel-edge check (SANDLOOM-T017) over ``kernel_edges.yml``.

ADR-0012 decisions 1, 2 and 7, invariants I-02 and I-03: the seeded register
passes on the tree it lands on, and each kind of edge planted into a small
kernel tree fails it (the mutation tests of KB-03 in
``design/kernel-boundary/migration-plan.md``).
"""

from __future__ import annotations

import sys
import time
import zipfile
from pathlib import Path
from typing import Any

import pytest
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import kernel_edges as ke

_EDGES = ke.REPO / "design" / "kernel-boundary" / "edges.yml"
_HEADER = "# Generated by `sandloom generate` (Public API 1.0): never edit by hand.\n"


def _tree(tmp_path: Path, files: dict[str, str]) -> Path:
    """A ``src`` tree with an empty kernel, one module package and
    ``files`` (paths relative to ``src``)."""
    src = tmp_path / "src"
    for package in ("sandloom", "sandloom/core", "sandloom/sdk", "sandloom/shared"):
        (src / package).mkdir(parents=True, exist_ok=True)
        (src / package / "__init__.py").write_text("")
    (src / "sandloom" / "main.py").write_text("")
    (src / "sandloom_crm").mkdir()
    (src / "sandloom_crm" / "__init__.py").write_text("")
    for rel, text in files.items():
        path = src / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return src


def _register(**data: Any) -> ke.Register:
    return ke.parse_register(data)


def _row(rid: str = "R1", **fields: Any) -> dict[str, Any]:
    row: dict[str, Any] = {
        "id": rid,
        "class": "b",
        "type": "naming",
        "scope": "runtime",
        "current_status": "open",
        "target": "fixed",
        "adr": "ADR-0012",
        "anchors": [{"path": "sandloom/core/x.py", "literal": '"crm"'}],
    }
    row.update(fields)
    return row


def _problems(src: Path, register: ke.Register) -> list[str]:
    return ke.check(register, src).problems


# --- the register on this tree --------------------------------------------------------


def test_the_seeded_register_passes() -> None:
    """Rules 1-5 hold for the register and the tree it lands on (I-02, I-03)."""
    outcome = ke.check(ke.load_register())
    assert not outcome.problems, "\n".join(outcome.problems)
    assert outcome.findings, "the scan found nothing: it would pass vacuously"


def test_the_register_holds_every_judged_row_of_the_design() -> None:
    """Each of the 46 rows of edges.yml is in the register with its kind,
    class, target and ADR; seeded open, B-N20 (documentation) retained, and
    the class (a) rows and family templates retained as protocol."""
    design = {e["id"]: e for e in yaml.safe_load(_EDGES.read_text())["edges"]}
    rows = {r.id: r for r in ke.load_register().rows}
    assert len(design) == 46
    for rid, edge in design.items():
        row = rows[rid]
        assert row.kind == edge.get("kind", "runtime"), rid
        assert (row.klass, row.target, row.adr) == (
            edge["class"],
            edge["target"],
            edge["adr"],
        ), rid
        assert {(a.path, a.literal, a.symbol) for a in row.anchors} >= {
            (a["path"], a.get("literal"), a.get("symbol")) for a in edge["anchors"]
        }, rid
    assert rows["B-N20"].current_status == "retained"
    assert rows["B-N20"].reason == "docstring example"
    protocol = [r for rid, r in rows.items() if rid not in design]
    assert len(protocol) == 20  # A1-A18 and the two family templates
    assert all(
        (r.klass, r.current_status, r.reason) == ("a", "retained", "protocol")
        for r in protocol
    )


def test_the_check_is_static_and_fast() -> None:
    """No extra I/O: the check reads source only; it stays well under the
    architecture suite's budget (measured: about 1 s on the full tree)."""
    started = time.perf_counter()
    ke.check(ke.load_register())
    assert time.perf_counter() - started < 15


