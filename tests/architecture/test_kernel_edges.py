def test_a_module_package_literal_and_a_constant_import_fail(tmp_path: Path) -> None:
    src = _tree(
        tmp_path,
        {
            "sandloom/core/x.py": (
                "import importlib\n"
                "def f():\n    return importlib.import_module('sandloom_crm.api')\n"
            ),
            "sandloom/sdk/y.py": (
                "import importlib\nPOLICY = 'sandloom_other.policy'\n"
                "def g():\n    return importlib.import_module(POLICY)\n"
            ),
        },
    )
    problems = _problems(src, _register())
    assert any("'sandloom_crm.api'" in p and "module-package" in p for p in problems)
    assert any(
        "sandloom/sdk/y.py:4" in p and "'sandloom_other.policy'" in p for p in problems
    )


def test_a_declared_setting_or_claim_key_fails(tmp_path: Path) -> None:
    src = _tree(
        tmp_path,
        {
            "sandloom/core/x.py": 'A = "CRM_API_KEY"\nB = "crm_api_key"\nC = "crm_plan"\n'
        },
    )
    register = _register(vocabulary={"settings": ["CRM_*"], "claim_keys": ["crm_plan"]})
    problems = _problems(src, register)
    assert sum("setting" in p for p in problems) == 2
    assert any("claim-key 'crm_plan'" in p for p in problems)


def test_a_protocol_word_is_not_a_finding(tmp_path: Path) -> None:
    src = _tree(tmp_path, {"sandloom/core/x.py": 'ROLE = "crm"\n'})
    assert _problems(src, _register(vocabulary={"protocol": ["crm"]})) == []


def test_a_row_anchor_covers_its_finding(tmp_path: Path) -> None:
    src = _tree(tmp_path, {"sandloom/core/x.py": 'MODULE = "crm"\n'})
    assert _problems(src, _register(edges=[_row()])) == []


def test_two_rows_with_equally_specific_anchors_are_ambiguous(tmp_path: Path) -> None:
    src = _tree(tmp_path, {"sandloom/core/x.py": 'MODULE = "crm"\n'})
    (problem,) = _problems(src, _register(edges=[_row("R1"), _row("R2")]))
    assert "more than one row (R1, R2)" in problem


def test_the_most_specific_anchor_wins(tmp_path: Path) -> None:
    src = _tree(tmp_path, {"sandloom/core/x.py": 'TABLE = {\n    "k": "crm",\n}\n'})
    by_symbol = _row(
        "WIDE", anchors=[{"path": "sandloom/core/x.py", "symbol": "TABLE"}]
    )
    outcome = ke.check(_register(edges=[by_symbol, _row("EXACT")]), src)
    assert outcome.problems == []
    assert any("module-name 'crm'" in e for e in outcome.evidence["EXACT"])
    assert not any("module-name" in e for e in outcome.evidence["WIDE"])


# --- dynamic imports -----------------------------------------------------------------


def test_a_computed_import_outside_the_loader_call_sites_fails(tmp_path: Path) -> None:
    source = (
        "import importlib\ndef load(name):\n    return importlib.import_module(name)\n"
    )
    src = _tree(tmp_path, {"sandloom/core/x.py": source})
    (problem,) = _problems(src, _register())
    assert "dynamic-import 'name'" in problem
    assert "cannot resolve" in problem
    listed = _register(
        loader_call_sites=[
            {"path": "sandloom/core/x.py", "symbol": "load", "reason": "the loader"}
        ]
    )
    assert _problems(src, listed) == []


def test_a_listed_call_site_without_an_import_is_stale(tmp_path: Path) -> None:
    src = _tree(tmp_path, {"sandloom/core/x.py": "def load(name):\n    return name\n"})
    register = _register(
        loader_call_sites=[
            {"path": "sandloom/core/x.py", "symbol": "load", "reason": "r"}
        ]
    )
    (problem,) = _problems(src, register)
    assert "loader call site sandloom/core/x.py load" in problem


# --- class (c): the wheel ------------------------------------------------------------


def test_a_module_file_in_the_wheel_fails(tmp_path: Path) -> None:
    src = _tree(
        tmp_path,
        {
            "sandloom/shared/contracts/crm_orders_v1.py": _HEADER + "X = 1\n",
            "sandloom/shared/events/crm.order.placed.v1.json": "{}\n",
            "sandloom/shared/events/core.auth.tokens_revoked.v1.json": "{}\n",
        },
    )
    problems = _problems(src, _register())
    assert len(problems) == 2
    assert any(
        "generated-file 'crm_orders_v1.py'" in p and "class c" in p for p in problems
    )
    assert any("'crm.order.placed.v1.json'" in p for p in problems)


def test_a_built_wheel_is_scanned_for_class_c(tmp_path: Path) -> None:
    wheel = tmp_path / "sandloom-0-py3-none-any.whl"
    with zipfile.ZipFile(wheel, "w") as archive:
        archive.writestr("sandloom/shared/contracts/crm_dto.py", _HEADER)
        archive.writestr("sandloom/core/x.py", "X = 1\n")
        archive.writestr("sandloom-0.dist-info/METADATA", _HEADER)
    found = ke.scan_wheel(ke.wheel_entries_from_wheel(wheel))
    assert [f.path for f in found] == ["sandloom/shared/contracts/crm_dto.py"]


