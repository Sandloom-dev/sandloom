"""The kernel-edge check (SANDLOOM-T017) over ``kernel_edges.yml``.

ADR-0012 decisions 1, 2 and 7, invariants I-02 and I-03: the seeded register
passes on the tree it lands on, and each kind of edge planted into a small
kernel tree fails it (the mutation tests of KB-03 in
``design/kernel-boundary/migration-plan.md``).
"""

