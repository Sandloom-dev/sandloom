"""The generator output the docs include is what a reader generates today.

``docs/snippets/generated`` (the how-to guides' ``sandloom add`` output) and the
generated files of the finished tutorial application
(``examples/tutorial``: snapshots, contract stubs, exported event
schemas) are regenerated by ``tools/docs/docs_generated.py``; this test runs its
``--check`` mode, so a framework change that alters them fails here until
``uv run python tools/docs/docs_generated.py`` rewrites them (round 8: the
tutorial app had no generated files and a stale stub).
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[2] / "tools" / "docs" / "docs_generated.py"


def test_the_docs_generator_output_is_current() -> None:
    proc = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"],
        capture_output=True,
        text=True,
        timeout=600,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr[-6000:]
