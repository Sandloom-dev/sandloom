#!/bin/bash

# Скрипт для запуска полной проверки кода с Mypy, Ruff и форматированием

echo "🔍 Запуск полной проверки кода..."
echo "================================="

# Переходим в корень backend (скрипт лежит в scripts/)
cd "$(dirname "$0")/../.."

# Проверяем, что у нас есть виртуальное окружение
if [ ! -d ".venv" ]; then
    echo "❌ Виртуальное окружение не найдено. Устанавливаем зависимости..."
    uv sync --dev
fi

# 1. Форматирование кода
echo "🎨 Форматирование кода с помощью Ruff..."
uv run ruff format src/
if [ $? -ne 0 ]; then
    echo "⚠️  Проблемы с форматированием"
fi

# 2. Линтинг
echo "🔧 Проверка стиля кода с помощью Ruff..."
uv run ruff check src/ --fix
if [ $? -ne 0 ]; then
    echo "⚠️  Найдены проблемы со стилем кода"
fi

# 3. Проверка типов
echo "📝 Проверка типов с помощью MyPy..."
uv run mypy src/

# Анализ результатов
mypy_exit_code=$?
if [ $mypy_exit_code -eq 0 ]; then
    echo "✅ Проверка типов завершена успешно!"
    echo "🎉 Все проверки пройдены!"
    exit 0
else
    echo "❌ Найдены ошибки типизации (код выхода: $mypy_exit_code)"
    echo ""
    echo "💡 Совет: Большинство ошибок связано с внешними библиотеками"
    echo "   и может быть безопасно проигнорировано в production."
    echo ""
    echo "📚 Подробнее читайте в docs/archive/backend-docs/MYPY_GUIDE.md"
    exit $mypy_exit_code
fi
