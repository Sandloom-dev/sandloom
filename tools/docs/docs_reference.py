REPO = Path(__file__).resolve().parents[2]
DOCS = REPO / "docs"
SDK_DIR = DOCS / "reference" / "sdk"
ERRORS_PAGE = DOCS / "reference" / "error-codes.md"
GENERATED = (
    "<!-- Generated by tools/docs/docs_reference.py from the code; do not edit. "
    "Regenerate: uv run python tools/docs/docs_reference.py -->"
)
_ADDRESS = re.compile(r" at 0x[0-9a-fA-F]+")
_REF_BLOCK = re.compile(
    r"\.\. sandloom-reference.*?\.\. end sandloom-reference\n?", re.S
)
_SECTION = re.compile(
    r"^(Args|Arguments|Parameters|Returns|Return|Yields|Raises|Attributes|"
    r"Example|Examples|Note|Notes|Guarantees|Warning|Warnings):\s*$"
)
_LIST_SECTIONS = {"Args", "Arguments", "Parameters", "Raises", "Attributes"}
_CODE_SECTIONS = {"Example", "Examples"}
_WIDTH = 88


# --------------------------------------------------------------------------- #
# Small text helpers


def _strip_address(text: str) -> str:
    return _ADDRESS.sub("", text)


def _escape_inline(text: str) -> str:
    """Markdown-safe prose: RST roles and literals to code spans, ``<`` escaped
    outside code spans."""
    text = re.sub(r":[a-z]+:`~?([^`]+)`", r"`\1`", text)
    text = text.replace("``", "`")
    parts = text.split("`")
    for i in range(0, len(parts), 2):  # outside code spans
        parts[i] = parts[i].replace("<", "&lt;")
    return "`".join(parts)


def _docstring_markdown(doc: str) -> str:
    """A docstring as Markdown: literal blocks fenced, Google sections listed."""
    lines = doc.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        section = _SECTION.match(line.strip()) if not line.startswith(" ") else None
        if section:
            name = section.group(1)
            block: list[str] = []
            i += 1
            while i < len(lines) and (lines[i].startswith(" ") or not lines[i].strip()):
                if not lines[i].strip() and (
                    i + 1 >= len(lines) or not lines[i + 1].startswith(" ")
                ):
                    break
                block.append(lines[i])
                i += 1
            body = textwrap.dedent("\n".join(block)).strip("\n")
            out.append(f"**{name}:**")
            out.append("")
            if name in _CODE_SECTIONS:
                code = body.replace(">>> ", "").replace("... ", "")
                out += ["```python", code, "```"]
            elif name in _LIST_SECTIONS:
                items: list[str] = []
                for raw in body.splitlines():
                    if raw and not raw.startswith(" "):
                        items.append(raw.strip())
                    elif items:
                        items[-1] += " " + raw.strip()
                for item in items:
                    head, sep, rest = item.partition(":")
                    if sep and " " not in head.split("(")[0].strip():
                        out.append(
                            f"- `{head.strip()}`: {_escape_inline(rest.strip())}"
                        )
                    else:
                        out.append(f"- {_escape_inline(item)}")
            else:
                out.append(_escape_inline(" ".join(body.split())))
            out.append("")
            continue
        if line.rstrip().endswith("::") and not line.startswith(" "):
            # An RST literal block: the indented lines that follow.
            head = line.rstrip()[:-2].rstrip()
            if head:
                out.append(_escape_inline(head + ":"))
            i += 1
            while i < len(lines) and not lines[i].strip():
                i += 1
            block = []
            if i < len(lines) and not lines[i].startswith(" "):
                # A literal block written without indentation: up to a blank line.
                while i < len(lines) and lines[i].strip():
                    block.append(lines[i])
                    i += 1
            while i < len(lines) and (lines[i].startswith(" ") or not lines[i].strip()):
                block.append(lines[i])
                i += 1
            code = textwrap.dedent("\n".join(block)).strip("\n")
            out += ["", "```python", code, "```", ""]
            continue
        if line.startswith("    ") and out and not out[-1].strip():
            # An indented block after a blank line: keep it as code.
            block = []
            while i < len(lines) and (lines[i].startswith(" ") or not lines[i].strip()):
                block.append(lines[i])
                i += 1
            code = textwrap.dedent("\n".join(block)).strip("\n")
            out += ["```text", code, "```", ""]
            continue
        out.append(_escape_inline(line))
        i += 1
    text = "\n".join(out).strip()
    return re.sub(r"\n{3,}", "\n\n", text)


