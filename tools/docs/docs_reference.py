# Signatures


class _Raw:
    def __init__(self, text: str) -> None:
        self.text = text

    def __repr__(self) -> str:
        return self.text


def _annotation_text(annotation: Any) -> Any:
    if annotation is inspect.Parameter.empty:
        return annotation
    if isinstance(annotation, str):
        return _Raw(annotation)
    return _Raw(_strip_address(inspect.formatannotation(annotation)))


def _signature(obj: Any) -> str | None:
    if isinstance(obj, type) and issubclass(obj, enum.Enum):
        return None  # the EnumType call signature differs between Python versions
    target = getattr(obj, "__wrapped__", None) if _is_fixture(obj) else obj
    try:
        sig = inspect.signature(target if target is not None else obj)
    except (TypeError, ValueError):
        return None
    params = [
        p.replace(annotation=_annotation_text(p.annotation))
        for p in sig.parameters.values()
    ]
    sig = sig.replace(
        parameters=params, return_annotation=_annotation_text(sig.return_annotation)
    )
    return _strip_address(str(sig))


def _wrap_signature(prefix: str, sig: str) -> str:
    one = f"{prefix}{sig}"
    if len(one) <= _WIDTH:
        return one
    # One parameter per line: split the top-level parameter list.
    close = _matching_paren(sig)
    inner, tail = sig[1:close], sig[close + 1 :]
    parts, depth, cur = [], 0, ""
    for ch in inner:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
            continue
        cur += ch
    if cur.strip():
        parts.append(cur.strip())
    body = "".join(f"    {p},\n" for p in parts)
    return f"{prefix}(\n{body}){tail}"


def _matching_paren(sig: str) -> int:
    depth = 0
    for i, ch in enumerate(sig):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return i
    return len(sig) - 1


def _is_fixture(obj: Any) -> bool:
    return type(obj).__name__ in {
        "FixtureFunctionDefinition",
        "FixtureFunctionMarker",
    } or (
        hasattr(obj, "_pytestfixturefunction")
        or hasattr(obj, "_fixture_function_marker")
    )


def _opaque(obj: Any) -> bool:
    """An object whose attribute access has effects (the lazy ``settings``)."""
    return any(c.__name__ == "BaseSettings" for c in type(obj).__mro__)


def _kind(obj: Any) -> str:
    if _opaque(obj):
        return "settings object"
    if _is_fixture(obj):
        return "fixture"
    if inspect.isclass(obj):
        if issubclass(obj, BaseException):
            return "exception"
        return "class"
    if inspect.iscoroutinefunction(obj):
        return "async function"
    if inspect.isfunction(obj) or inspect.isbuiltin(obj) or inspect.ismethod(obj):
        return "function"
    if type(obj).__name__ in {"_AnnotatedAlias", "Annotated"}:
        return "annotated type"
    if callable(obj) and not isinstance(
        obj, (str, bytes, int, float, tuple, dict, list)
    ):
        return "callable"
    return "constant"


def _definition(name: str, obj: Any) -> str:
    kind = _kind(obj)
    if kind == "settings object":
        return f"{name}: Settings  # loaded and validated at first attribute access"
    if kind == "annotated type":
        return f"{name} = {_strip_address(repr(obj)).replace('typing.', '')}"
    if kind == "constant":
        if not isinstance(
            obj, (str, int, float, bool, tuple, frozenset, list, dict, type(None))
        ):
            # Never repr an arbitrary object: a lazy proxy (``settings``) would
            # validate the environment, and a repr is not an API.
            return f"{name}: {type(obj).__name__}"
        if isinstance(obj, frozenset):  # set order varies per process
            value = "frozenset({" + ", ".join(sorted(repr(v) for v in obj)) + "})"
        else:
            value = _strip_address(repr(obj))
        if len(value) > 160:
            value = value[:157] + "..."
        return f"{name}: {type(obj).__name__} = {value}"
    if kind in {"class", "exception"}:
        bases = ", ".join(
            b.__name__ for b in getattr(obj, "__bases__", ()) if b is not object
        )
        head = f"class {name}({bases})" if bases else f"class {name}"
        sig = _signature(obj)
        if sig and sig not in {"(*args, **kwargs)", "()"}:
            return _wrap_signature(head, sig)
        return head
    sig = _signature(obj) or "(...)"
    prefix = "async def " if kind == "async function" else "def "
    if kind == "fixture":
        prefix = "@pytest.fixture\ndef "
    return _wrap_signature(f"{prefix}{name}", sig)


def _methods(obj: Any) -> list[tuple[str, str, str]]:
    """Public methods and properties defined on the class itself."""
    if _opaque(obj) or not inspect.isclass(obj) or issubclass(obj, BaseException):
        return []
    found = []
    for attr, value in vars(obj).items():
        if attr.startswith("_"):
            continue
        func = value
        if isinstance(value, (staticmethod, classmethod)):
            func = value.__func__
        if isinstance(value, property):
            doc = inspect.getdoc(value) or ""
            found.append((attr, f"{attr}  (property)", doc))
            continue
        if not callable(func) or inspect.isclass(func):
            continue
        sig = _signature(func) or "(...)"
        prefix = "async def " if inspect.iscoroutinefunction(func) else "def "
        if isinstance(value, staticmethod):
            prefix = "@staticmethod\n" + prefix
        elif isinstance(value, classmethod):
            prefix = "@classmethod\n" + prefix
        found.append(
            (attr, _wrap_signature(f"{prefix}{attr}", sig), inspect.getdoc(func) or "")
        )
    return found


def _summary(obj: Any) -> str:
    doc = None
    if not _opaque(obj) and not isinstance(obj, (str, int, float, tuple)):
        doc = inspect.getdoc(obj)
    if _kind(obj) in {"constant", "annotated type", "settings object"}:
        doc = None
    first = (doc or "").strip().split("\n\n")[0].replace("\n", " ")
    if first.endswith("::"):
        first = first[:-1]
    first = _escape_inline(first).replace("|", "\\|")
    return first if len(first) <= 140 else first[:137].rstrip() + "..."


