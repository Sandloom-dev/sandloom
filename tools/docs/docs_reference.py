def render_errors() -> str:
    from sandloom.core import error_codes

    entries = list(error_codes.CATALOGUE)
    kinds = {
        "check": "Static checks (`sandloom check`)",
        "boot": "Startup refusals (`create_app`, `sandloom check --boot`)",
        "runtime": "Runtime errors",
        "test": "Test-harness and snapshot gates (`sandloom test`)",
    }

    def status(e: Any) -> str:
        if e.retired:
            return "retired (never reused)"
        if e.planned:
            return f"planned: {e.planned}"
        return "active"

    out = [
        "---",
        "title: Error catalogue",
        "description: Every Sandloom error code — its slug, what happened, the fix and "
        "its status, generated from sandloom.core.error_codes.",
        "---",
        "",
        GENERATED,
        "",
        "# Error catalogue",
        "",
        "Every framework diagnostic carries a stable code. A message at the "
        "failure site links directly to its section on the website and gives "
        "an offline help command:",
        "",
        "```text",
        "error[SANDLOOM-B008]: route POST /api/v1/notes/ is neither authenticated nor public()",
        "  --> notes/api.py:12 (create_note)",
        "  fix: ...",
        "  docs: https://sandloom.dev/docs/reference/error-codes/#sandloom-b008",
        "  help: sandloom explain SANDLOOM-B008",
        "```",
        "",
        "`sandloom explain <code>` (or the slug, e.g. `sandloom explain route-policy`) "
        "prints the long form below; `sandloom explain --list` lists every code. "
        "Families: `SANDLOOM-C` static `sandloom check` rules, `SANDLOOM-B` startup refusals, "
        "`SANDLOOM-R` runtime errors, `SANDLOOM-T` test-harness and snapshot gates. Codes "
        "are never reused or renumbered; a retired code stays listed.",
        "",
        "## Index",
        "",
        "| Code | Slug | Kind | What happened | Status |",
        "| --- | --- | --- | --- | --- |",
    ]
    for e in entries:
        title = _escape_inline(e.title).replace("|", "\\|")
        out.append(
            f"| [`{e.code}`](#{e.code.lower()}) | `{e.slug}` | {e.kind} | {title} "
            f"| {status(e)} |"
        )
    out.append("")
    for kind, heading in kinds.items():
        group = [e for e in entries if e.kind == kind]
        if not group:
            continue
        out += [f"## {heading}", ""]
        for e in group:
            out += [f"### {e.code}", ""]
            out += [
                f"**{_escape_inline(e.title)}**",
                "",
                f"Slug: `{e.slug}` · kind: {e.kind} · status: {status(e)}",
                "",
                "**What happened and why it matters**",
                "",
                _docstring_markdown(e.explain),
                "",
                f"**Fix:** {_escape_inline(e.fix)}",
                "",
            ]
            if e.docs:
                out += [f"**More:** `{e.docs}`", ""]
    out += [
        "## Related reading",
        "",
        "- [CLI reference](cli.md)",
        "- [Getting help](../getting-started/help.md)",
        "",
    ]
    return "\n".join(out).rstrip() + "\n"


