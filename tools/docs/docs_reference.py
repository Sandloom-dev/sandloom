def expected_pages() -> dict[Path, str]:
    from tools.docs.gen_config_reference import render_pages as config_pages
    from tools.docs.gen_reference_pages import render_pages as route_pages

    pages = sdk_pages()
    pages[ERRORS_PAGE] = render_errors()
    for family in (config_pages(), route_pages()):
        pages.update({DOCS / name: text for name, text in family.items()})
    return pages


def stale(pages: dict[Path, str]) -> list[Path]:
    found = [
        path
        for path, text in pages.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != text
    ]
    known = set(pages)
    found += [p for p in SDK_DIR.rglob("*.md") if p not in known]  # orphans
    return found


def write(pages: dict[Path, str]) -> list[Path]:
    written = []
    for path, text in pages.items():
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    known = set(pages)
    for orphan in SDK_DIR.rglob("*.md"):
        if orphan not in known:
            orphan.unlink()
            written.append(orphan)
    return written


def _ensure_importable() -> None:
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    src = REPO / "src"
    if str(src) not in sys.path:
        sys.path.insert(0, str(src))


def main(argv: list[str] | None = None, *, out: Callable[[str], None] = print) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when stale")
    args = parser.parse_args(argv)
    _ensure_importable()
    pages = expected_pages()
    if args.check:
        bad = stale(pages)
        for path in bad:
            out(f"stale: {path.relative_to(REPO)}")
        return 1 if bad else 0
    for path in write(pages):
        out(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
