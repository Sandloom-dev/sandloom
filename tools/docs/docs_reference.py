def _public_modules() -> list[ModuleType]:
    from sandloom.sdk._prim.docs import (
        public_modules,
    )  # the one list `sandloom docs` uses

    return public_modules()


def _page_path(module: str) -> Path:
    from sandloom.sdk._prim.docs import doc_page

    return REPO / doc_page(module)


def _rel(from_module: str, to_module: str) -> str:
    """Relative link from one module page to another."""
    src = _page_path(from_module).parent
    dst = _page_path(to_module)
    return Path(_relpath(dst, src)).as_posix()


def _relpath(path: Path, start: Path) -> str:
    import os

    return os.path.relpath(path, start)


def _module_doc(module: ModuleType) -> str:
    doc = inspect.getdoc(module) or ""
    doc = _REF_BLOCK.sub("", doc)
    # The H0 status notes describe the build, not the API.
    doc = re.sub(
        r"\n*Public API 1\.0 \(spec §2\.2, Appendix C\)\. Names marked new in §2\.2 are\n"
        r"typed stubs until their hand-off \(they raise ``NotImplementedError``\)\.\n*",
        "\n\n",
        doc,
    )
    return _docstring_markdown(doc.strip())


def _home_of(name: str, modules: list[ModuleType]) -> ModuleType | None:
    """The themed module that exports ``name`` (not the root), preferring the
    one whose beginner tier holds it."""
    for module in modules:
        if module.__name__ != "sandloom.sdk" and name in getattr(
            module, "__beginner__", ()
        ):
            return module
    for module in modules:
        if module.__name__ != "sandloom.sdk" and name in getattr(module, "__all__", ()):
            return module
    return None


def _entry(name: str, obj: Any) -> list[str]:
    lines = [f"### `{name}`", "", "```python", _definition(name, obj), "```", ""]
    doc = None
    if _kind(obj) not in {"constant", "annotated type", "settings object"}:
        doc = inspect.getdoc(obj)
    if doc:
        lines += [_docstring_markdown(doc), ""]
    else:
        lines += ["*(no docstring)*", ""]
    for attr, signature, mdoc in _methods(obj):
        lines += [f"#### `{name}.{attr}`", "", "```python", signature, "```", ""]
        if mdoc:
            lines += [_docstring_markdown(mdoc), ""]
    return lines


def _beginner_and_advanced(module: ModuleType) -> tuple[list[str], list[str]]:
    names = list(getattr(module, "__all__", ()))
    beginner = sorted(
        (n for n in getattr(module, "__beginner__", ()) if n in names), key=str.lower
    )
    return beginner, sorted((n for n in names if n not in beginner), key=str.lower)


def _anchors(module: ModuleType) -> dict[str, str]:
    """Each name's heading id on its page, in page order. The site numbers a repeated
    id, and a method heading counts: `Event.meta` takes `eventmeta` before `EventMeta`,
    and `Cache` takes `cache` before the function `cache`."""
    seen: dict[str, int] = {}

    def heading_id(text: str) -> str:
        slug = text.lower().replace(".", "")
        seen[slug] = seen.get(slug, 0) + 1
        return slug if seen[slug] == 1 else f"{slug}_{seen[slug] - 1}"

    anchors: dict[str, str] = {}
    beginner, advanced = _beginner_and_advanced(module)
    for name in (*beginner, *advanced):
        anchors[name] = heading_id(name)
        for attr, _signature_text, _doc in _methods(getattr(module, name)):
            heading_id(f"{name}.{attr}")
    return anchors


def _table(names: Iterable[str], module: ModuleType) -> list[str]:
    rows = ["| Name | Kind | Summary |", "| --- | --- | --- |"]
    anchors = _anchors(module)
    for name in names:
        obj = getattr(module, name)
        rows.append(
            f"| [`{name}`](#{anchors[name]}) | {_kind(obj)} | {_summary(obj)} |"
        )
    return rows


def render_module(module: ModuleType) -> str:
    """The reference page of one public ``sandloom.sdk`` module."""
    beginner, advanced = _beginner_and_advanced(module)
    out = [
        "---",
        f"title: {module.__name__}",
        "description: "
        + json.dumps(
            f"Reference of {module.__name__}: every public name with its "
            "signature, beginner names first."
        ),
        "---",
        "",
        GENERATED,
        "",
        f"# `{module.__name__}`",
        "",
        _module_doc(module),
        "",
        f"`from {module.__name__} import <name>`. Signatures in a terminal: "
        "`sandloom docs <name>`. Beginner names are the ones generated code and the "
        "examples use; any other name is advanced (mark its import line "
        "`# sandloom: advanced <reason>` in generated code and examples).",
        "",
    ]
    if beginner:
        out += ["## Start with (beginner)", "", *_table(beginner, module), ""]
    if advanced:
        out += ["## Advanced", "", *_table(advanced, module), ""]
    if beginner:
        out += ["## Beginner names", ""]
        for name in beginner:
            out += _entry(name, getattr(module, name))
    if advanced:
        out += ["## Advanced names", ""]
        for name in advanced:
            out += _entry(name, getattr(module, name))
    guides = {
        "app": ("Application quickstart", "getting-started/index.md"),
        "module": ("Add a module", "guides/add-module.md"),
        "web": ("Route policy", "concepts/route-policy.md"),
        "data": ("Units and transactions", "concepts/units.md"),
        "tenant": ("Tenant isolation", "concepts/multi-tenancy.md"),
        "events": ("Publish and consume events", "guides/add-event.md"),
        "effects": ("Deduplicate effects", "guides/effect-deduplication.md"),
        "tasks": ("Background tasks", "concepts/background-tasks.md"),
        "contracts": ("Provide and call a contract", "guides/add-contract.md"),
        "authz": ("Authorization policies", "concepts/authorization.md"),
        "sagas": ("Add a saga", "guides/add-saga.md"),
        "projections": ("Build a projection", "guides/add-projection.md"),
        "infra": (
            "Infrastructure capabilities",
            "concepts/capabilities-and-infrastructure.md",
        ),
        "security": ("Revoke sessions", "guides/session-revocation.md"),
        "errors": ("Error catalogue", "reference/error-codes.md"),
        "migrations": ("Run migrations", "guides/migrations.md"),
        "tooling": ("Generate contracts and snapshots", "guides/generate.md"),
    }
    key = module.__name__.removeprefix("sandloom.sdk.")
    if key.startswith("testing"):
        example = ("Testing examples and fixtures", "reference/testing.md")
    else:
        example = guides.get(key, ("How-to guides", "guides/index.md"))
    out += ["## Examples and related guides", ""]
    for label, target in [example, ("Python API overview", "reference/sdk/index.md")]:
        link = Path(
            _relpath(DOCS / target, _page_path(module.__name__).parent)
        ).as_posix()
        out.append(f"- [{label}]({link})")
    return "\n".join(out).rstrip() + "\n"


def render_index(modules: list[ModuleType]) -> str:
    """``docs/reference/sdk/index.md``: the namespace, its modules, the tiers."""
    root = next(m for m in modules if m.__name__ == "sandloom.sdk")
    out = [
        "---",
        "title: sandloom.sdk",
        "description: The Public API 1.0 namespace — every public module, the 29 "
        "beginner names and where each name lives.",
        "---",
        "",
        GENERATED,
        "",
        "# `sandloom.sdk`: the Python API",
        "",
        _module_doc(root),
        "",
        "## The beginner names",
        "",
        "These 21 code names are importable from `sandloom.sdk` directly; the six "
        "testing names (`client`, `as_user`, `published`, `deliver`, "
        "`fake_contract`, `fake_access_fact`) come from `sandloom.sdk.testing` and "
        "its pytest plugin. Each links to its entry on its home page.",
        "",
        "| Name | Home | Kind | Summary |",
        "| --- | --- | --- | --- |",
    ]
    for name in sorted(getattr(root, "__all__", ()), key=str.lower):
        home = _home_of(name, modules)
        obj = getattr(root, name)
        link = (
            f"[`{name}`]({_rel('sandloom.sdk', home.__name__)}#{_anchors(home)[name]})"
            if home
            else f"`{name}`"
        )
        where = f"`{home.__name__}`" if home else "`sandloom.sdk`"
        out.append(f"| {link} | {where} | {_kind(obj)} | {_summary(obj)} |")
    testing = next((m for m in modules if m.__name__ == "sandloom.sdk.testing"), None)
    plugin = next(
        (m for m in modules if m.__name__ == "sandloom.sdk.testing.plugin"), None
    )
    for mod in (testing, plugin):
        if mod is None:
            continue
        for name in sorted(getattr(mod, "__beginner__", ()), key=str.lower):
            obj = getattr(mod, name)
            anchor = _anchors(mod)[name]
            link = f"[`{name}`]({_rel('sandloom.sdk', mod.__name__)}#{anchor})"
            out.append(
                f"| {link} | `{mod.__name__}` | {_kind(obj)} | {_summary(obj)} |"
            )
    out += [
        "",
        "## Modules",
        "",
        "| Module | Beginner names | Names | Summary |",
        "| --- | ---: | ---: | --- |",
    ]
    for module in modules:
        if module.__name__ == "sandloom.sdk":
            continue
        names = getattr(module, "__all__", ())
        beginner = [n for n in getattr(module, "__beginner__", ()) if n in names]
        summary = _summary(module)
        out.append(
            f"| [`{module.__name__}`]({_rel('sandloom.sdk', module.__name__)}) | "
            f"{len(beginner)} | {len(names)} | {summary} |"
        )
    out += [
        "",
        "## Levels",
        "",
        "Level 1 (declarative: `define_module` discovery, `module_router`, "
        "`Event`, `on`, `contract`, `command`, `Contract`, typed saga steps, "
        "`Projection`) is built only from level 2 (the primitives these pages "
        "list as advanced). The kernel (level 3) is never imported by a module. "
        "See [Module internals](../../concepts/module-internals.md).",
        "",
    ]
    return "\n".join(out).rstrip() + "\n"


def sdk_pages() -> dict[Path, str]:
    modules = _public_modules()
    pages = {SDK_DIR / "index.md": render_index(modules)}
    for module in modules:
        if module.__name__ == "sandloom.sdk":
            continue
        pages[_page_path(module.__name__)] = render_module(module)
    return pages


