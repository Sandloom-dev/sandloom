"""Generate the committed reference pages from code, and check they are current.

Two generated families, both committed so agents read them on disk and in the
wheel without a docs build (docs strategy §6.3):

* ``docs/reference/sdk/<module>.md`` — one page per public ``sandloom.sdk`` module
  (the paths ``sandloom docs`` and every module's reference block name): its
  beginner names first, then the advanced ones, each with its exact signature
  (``inspect.signature``) and its docstring.
* ``docs/reference/error-codes.md`` — the error catalogue
  (``sandloom.core.error_codes``): every code with its slug, kind, what happened,
  the fix and its status.

Usage (from the repository root, so ``sandloom`` imports from the checkout)::

    uv run python tools/docs/docs_reference.py           # rewrite the pages
    uv run python tools/docs/docs_reference.py --check   # exit 1 when stale

``tools/docs/docs_site.py`` checks these pages before building or serving with
Zensical. Configuration, tier and route references are generated here too.
"""

