"""``architecture_rules.yml`` — the import-boundary manifest ``sandloom check`` reads.

One schema serves the framework tree (``architecture_rules.yml``) and an
application generated by ``sandloom new``. Keys (paths are relative to the manifest):

``modules_path``     directory holding the business-module packages
                     (framework: ``src/sandloom``; app: ``<app>/modules``)
``modules_package``  dotted package of that directory (``<app>.modules``);
                     default derived from ``modules_path`` relative to
                     ``source_root``. Empty (``""``, ``modules_path`` equal to
                     ``source_root``): the modules are top-level packages —
                     the framework tree (``sandloom_identity``, ...) and any
                     repository of ecosystem module packages
``source_root``      the ``sys.path`` root the packages are importable from
                     (framework: ``src``; app: ``.``) — used to resolve relative
                     imports
``kernel_package``   optional package under ``modules_path`` that is the kernel
                     (framework: ``sandloom``): only layer-checked, never a
                     module. Only the framework tree (top-level modules, kernel
                     ``sandloom``, and ``<modules_path>/sandloom`` resolving to
                     the kernel this process runs) may set it: SANDLOOM-C040
``exclude_modules``  packages under ``modules_path`` that are not business modules
``framework_packages`` packages under ``modules_path`` that are framework code
                     above the kernel (framework: ``sdk``, Public API 1.0):
                     never a module and not import-checked as one; their
                     boundaries are import-linter contracts. Only the
                     framework tree may set it: SANDLOOM-C040
``public_api``       the ``sandloom.sdk`` modules a business module may import.
                     A ``sandloom.core.*`` entry (or a prefix that covers
                     ``sandloom.core``) is refused: SANDLOOM-C038
``shared_api``       further framework prefixes a module may import
                     (default ``[sandloom.shared]``). An entry that covers
                     ``sandloom.core`` beyond its test surfaces is refused:
                     SANDLOOM-C041
``test_api``         framework test surfaces a module's TESTS may import on top
                     of ``public_api`` + ``shared_api`` + the module's own
                     package (default ``[sandloom.core.testing,
                     sandloom.core.contract_testing]``). Another entry that
                     covers ``sandloom.core`` is refused: SANDLOOM-C041
``forbidden_patterns`` / ``layers``  as documented in the framework manifest.
``allowlist``        a list of ``{file: <glob>, imports: [<glob>, ...]}``: the
                     imports a file may keep (``file`` is relative to the
                     manifest). In an application an entry that admits
                     ``sandloom.core`` or a private ``sandloom.sdk`` layer
                     (``["sandloom.core"]``, ``sandloom.cor?`` too) is refused;
                     in the framework tree it is refused unless its
                     ``imports`` are specific modules and its ``file`` names
                     the files of one business module: SANDLOOM-C042
``shared_package``   the contract-DTO package that receives the generated
                     contract stubs (``<pkg>/contracts/``) and the exported
                     producer event schemas (``<pkg>/events/``), Public API
                     1.0 spec §5.2, §5.3 (default: ``<app>.shared`` in an
                     application; none in a tree of top-level module
                     packages, where every module keeps its own generated
                     copies in ``<module>/_generated/``, ADR-0013)
``tenant_scope_exempt`` tables with a tenant-like column (``tenant_id``,
                     ``organization_id``, ...) that deliberately do
                     not inherit ``TenantScoped`` (rule
                     ``tenant-scoped-models``): a list of
                     ``{table: <name>, reason: <why>}``; both keys are
                     required, and an entry matching no such table fails the
                     check (stale).

The former key ``allowed_framework_imports`` is refused (split it into
``public_api`` and ``shared_api``).
"""

from __future__ import annotations

import fnmatch
import functools
import importlib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, cast

from sandloom.core import error_codes

#: The framework's ENFORCED public import contract for business modules: the
#: ``sandloom.sdk`` modules (Public API 1.0). Used when a manifest names none
#: (and mirrored by architecture_rules.yml). No ``sandloom.core`` module is on
#: it: ``load_rules`` refuses a manifest that lists one (SANDLOOM-C038).
DEFAULT_PUBLIC_API: tuple[str, ...] = (
    "sandloom.sdk",
    "sandloom.sdk.app",
    "sandloom.sdk.authz",
    "sandloom.sdk.contracts",
    "sandloom.sdk.data",
    "sandloom.sdk.effects",
    "sandloom.sdk.errors",
    "sandloom.sdk.events",
    "sandloom.sdk.infra",
    "sandloom.sdk.migrations",
    "sandloom.sdk.module",
    "sandloom.sdk.projections",
    "sandloom.sdk.sagas",
    "sandloom.sdk.security",
    "sandloom.sdk.tasks",
    "sandloom.sdk.tenant",
    "sandloom.sdk.testing",
    "sandloom.sdk.testing.fixtures",
    "sandloom.sdk.tooling",
    "sandloom.sdk.web",
)
#: Forbidden whatever the manifest says: the private layers of ``sandloom.sdk``
#: (``_decl``, ``_prim``, ``_x.y``), which the prefix match of ``public_api``
#: would otherwise admit. ``load_rules`` merges them into ``forbidden_patterns``.
DEFAULT_FORBIDDEN_PATTERNS: tuple[str, ...] = (
    "sandloom.sdk._*",
    "sandloom.sdk.*._*",
)
#: The catalogue code of a ``public_api`` that lists a ``sandloom.core`` module.
CORE_IN_PUBLIC_API_CODE = "SANDLOOM-C038"
#: ``framework_packages`` or ``kernel_package`` outside the framework tree: each
#: package it names is exempt from every rule, so an application may not set it.
KERNEL_EXEMPT_PACKAGE_CODE = "SANDLOOM-C040"
#: A ``test_api`` or ``shared_api`` entry that covers ``sandloom.core`` beyond the
#: framework's test surfaces: a module's tests would import the kernel.
CORE_IN_API_LIST_CODE = "SANDLOOM-C041"
#: An ``allowlist`` entry that admits ``sandloom.core`` (or a private
#: ``sandloom.sdk`` layer) for more than named modules of one business module.
CORE_IN_ALLOWLIST_CODE = "SANDLOOM-C042"
#: The catalogue codes ``load_rules`` raises itself, as a refusal of the manifest
#: before any module is scanned. They are ``check``-kind catalogue entries but no
#: archcheck rule (``runner.RULES``): the catalogue invariant in
#: ``core/tests/test_error_codes.py`` names them from here and proves each one is
#: raised by ``load_rules``.
MANIFEST_REFUSAL_CODES: tuple[str, ...] = (
    CORE_IN_PUBLIC_API_CODE,
    KERNEL_EXEMPT_PACKAGE_CODE,
    CORE_IN_API_LIST_CODE,
    CORE_IN_ALLOWLIST_CODE,
)
DEFAULT_SHARED_API: tuple[str, ...] = ("sandloom.shared",)
DEFAULT_TEST_API: tuple[str, ...] = (
    "sandloom.core.testing",
    "sandloom.core.contract_testing",
)


class ManifestError(ValueError):
    """The manifest is missing, unreadable or inconsistent."""


@dataclass
class ArchRules:
    root: Path
    modules_path: Path
    modules_package: str
    source_root: Path
    kernel_package: str | None = None
    exclude_modules: set[str] = field(default_factory=set)
    framework_packages: set[str] = field(default_factory=set)
    public_api: set[str] = field(default_factory=lambda: set(DEFAULT_PUBLIC_API))
    shared_api: set[str] = field(default_factory=lambda: set(DEFAULT_SHARED_API))
    test_api: set[str] = field(default_factory=lambda: set(DEFAULT_TEST_API))
    forbidden_patterns: list[str] = field(default_factory=list)
    allowlist: list[dict[str, Any]] = field(default_factory=list)
    layers_enabled: bool = False
    layers_defs: dict[str, set[str]] = field(default_factory=dict)
    layer_rules: list[tuple[str, set[str]]] = field(default_factory=list)
    #: ``table -> reason`` exempt from the ``tenant-scoped-models`` rule.
    tenant_scope_exempt: dict[str, str] = field(default_factory=dict)
    #: The contract-DTO package of generated stubs and exported event schemas.
    shared_package: str | None = None

    @property
    def top_level_modules(self) -> bool:
        """The business modules are top-level packages (``modules_package``
        empty): the framework tree or an ecosystem module repository."""
        return not self.modules_package

    def module_package(self, module: str) -> str:
        """The import path of business module ``module`` (a directory name)."""
        return f"{self.modules_package}.{module}" if self.modules_package else module

    @property
    def shared_dto_package(self) -> str | None:
        """``shared_package``, else ``<app>.shared`` in an application; ``None``
        in a tree of top-level module packages (the framework tree, an
        ecosystem repository): the kernel ships no generated stub or DTO copy
        and each module holds its own in ``<module>/_generated/``."""
        if self.shared_package:
            return self.shared_package
        top = self.modules_package.split(".")[0]
        return f"{top}.shared" if top else None

    @property
    def shared_dir(self) -> Path | None:
        """The directory of :attr:`shared_dto_package` under ``source_root``."""
        package = self.shared_dto_package
        if package is None:
            return None
        return self.source_root.joinpath(*package.split("."))

    @property
    def is_framework_tree(self) -> bool:
        """The framework checkout: its kernel is the ``sandloom`` package and
        its modules are the top-level ecosystem packages next to it."""
        return self.top_level_modules and self.kernel_package == "sandloom"

    @property
    def model_roots(self) -> tuple[str, ...]:
        """Top-level packages whose ``.models`` count as ORM in endpoint files."""
        if self.top_level_modules:
            return ("sandloom", *self.business_modules())
        return ("sandloom", self.modules_package.split(".")[0])

    def business_modules(self) -> list[str]:
        excluded = set(self.exclude_modules) | self.framework_packages
        if self.kernel_package:
            excluded.add(self.kernel_package)
        if not self.modules_path.is_dir():
            raise ManifestError(
                f"`modules_path` is not a directory: {self.modules_path}"
            )
        return sorted(
            d.name
            for d in self.modules_path.iterdir()
            if d.is_dir()
            and (d / "__init__.py").exists()
            and not d.name.startswith(("_", "."))
            and d.name not in excluded
        )


def _str_list(data: dict[str, Any], key: str) -> list[str]:
    value = data.get(key) or []
    if not isinstance(value, list):
        raise ManifestError(f"`{key}` must be a list")
    return [str(v) for v in value]


def _covers_core(entry: str) -> bool:
    """``entry`` would let a module import ``sandloom.core``: a ``sandloom.core``
    module, or ``sandloom`` itself (the import check matches entries by
    prefix)."""
    return entry in ("sandloom", "sandloom.core") or entry.startswith("sandloom.core.")


def _covers_core_beyond_test_surface(entry: str) -> bool:
    """``entry`` would let a module's tests import the kernel: ``sandloom``,
    ``sandloom.core`` or a ``sandloom.core`` module that is not one of the
    framework's test surfaces (:data:`DEFAULT_TEST_API`)."""
    return _covers_core(entry) and not any(
        entry == surface or entry.startswith(f"{surface}.")
        for surface in DEFAULT_TEST_API
    )


@functools.lru_cache(maxsize=1)
def _kernel_modules() -> tuple[str, ...]:
    """The dotted names of the kernel: ``sandloom``, every ``sandloom.core`` module
    and the private layers of ``sandloom.sdk`` (``_decl``, ``_prim``, ``_x``). Read
    from the installed tree by file name; nothing is imported."""
    package = Path(__file__).resolve().parents[2]
    names = ["sandloom", "sandloom.core"]
    for sub in ("core", "sdk"):
        for py in sorted((package / sub).rglob("*.py")):
            parts = [sub, *py.relative_to(package / sub).with_suffix("").parts]
            if parts[-1] == "__init__":
                parts.pop()
            private = any(p.startswith("_") and p != "__init__" for p in parts[1:])
            if sub == "core" or private:
                names.append(".".join(("sandloom", *parts)))
    return tuple(dict.fromkeys(names))


def _kernel_unit(name: str) -> str:
    """The module a kernel name belongs to: ``sandloom.core.database`` for
    ``sandloom.core.database.engine``, ``sandloom.sdk._prim`` for a module of that
    private layer."""
    parts = name.split(".")
    if parts[:2] == ["sandloom", "core"] and len(parts) > 2:
        return ".".join(parts[:3])
    if parts[:2] == ["sandloom", "sdk"]:
        for index, part in enumerate(parts[2:], start=2):
            if part.startswith("_"):
                return ".".join(parts[: index + 1])
    return name


def _admits_kernel(pattern: str) -> tuple[bool, bool]:
    """``(admits, broad)`` of an ``allowlist`` import pattern.

    ``admits``: it excuses a ``sandloom.core`` module or a private layer of
    ``sandloom.sdk``: it matches a real one, or names one (``sandloom.core.x``).
    ``broad``: it matches more than one of them (``*``, ``sandloom*``,
    ``sandloom.core*``, ``sandloom.core.*``, ``sandloom.sdk._*``, ``s*.core.d*``),
    not one module and its submodules (``sandloom.core.database*``)."""
    matched = [n for n in _kernel_modules() if fnmatch.fnmatch(n, pattern)]
    named = pattern == "sandloom.core" or pattern.startswith(
        ("sandloom.core.", "sandloom.sdk._")
    )
    return bool(matched) or named, len({_kernel_unit(n) for n in matched}) > 1


def _names_one_module(file_pattern: str, modules_rel: str) -> bool:
    """``file_pattern`` can match files of one business module only: it starts
    with ``<modules_path>/<module>/`` (relative to the manifest) and the module
    segment holds no glob."""
    prefix = "" if modules_rel in ("", ".") else f"{modules_rel.rstrip('/')}/"
    if ".." in file_pattern.split("/") or not file_pattern.startswith(prefix):
        return False
    module, slash, _rest = file_pattern[len(prefix) :].partition("/")
    return bool(module) and bool(slash) and not any(c in module for c in "*?[")


def _kernel_dir() -> Path:
    """The directory of the ``sandloom`` package this process runs: the real
    kernel, with symlinks resolved (an editable install points at the checkout)."""
    return Path(__file__).resolve().parents[2]


def _is_framework_tree(
    modules_path: Path, modules_package: str, kernel: str | None
) -> bool:
    """The manifest describes the framework's own checkout: top-level modules,
    kernel ``sandloom``, and ``<modules_path>/sandloom`` IS the kernel this
    process runs. A directory named ``sandloom/core`` made under ``modules_path``
    is not: the resolved paths are compared, not the names."""
    return (
        not modules_package
        and kernel == "sandloom"
        and (modules_path / "sandloom").resolve() == _kernel_dir()
    )


def _kernel_elsewhere_hint(
    modules_path: Path, modules_package: str, kernel: str | None
) -> str:
    """The cause to name when a manifest has the shape of the framework's own tree
    (top-level modules, ``kernel_package: sandloom``, a ``sandloom`` directory
    under ``modules_path``) and is refused anyway: that ``sandloom`` is not the
    kernel this process runs, as when another checkout's environment checks it.
    Empty for a manifest that does not look like it."""
    if (
        modules_package
        or kernel != "sandloom"
        or not (modules_path / "sandloom").is_dir()
    ):
        return ""
    return (
        "; the `sandloom` package under `modules_path` is not the kernel this "
        f"process runs ({_kernel_dir()}): in the framework's own checkout, run the "
        "check with that checkout's environment (`uv run sandloom check`), not "
        "another checkout's"
    )


def _refuse_kernel_exemptions(
    path: Path,
    *,
    framework_tree: bool,
    kernel: str | None,
    framework: set[str],
    elsewhere: str = "",
) -> None:
    """``kernel_package`` and ``framework_packages`` take every package they name
    out of the import check and out of the business modules, so only the
    framework tree may set them (:func:`_is_framework_tree`). A manifest that
    only spells the top-level modules and kernel ``sandloom``, or fakes the
    kernel directory under ``modules_path``, is an application dressed as the
    framework."""
    if framework_tree:
        return
    named = [
        *([f"`kernel_package: {kernel}`"] if kernel else []),
        *(
            [f"`framework_packages: [{', '.join(sorted(framework))}]`"]
            if framework
            else []
        ),
    ]
    if not named:
        return
    raise ManifestError(
        error_codes.render(
            KERNEL_EXEMPT_PACKAGE_CODE,
            f"{' and '.join(named)} exempts the package it names from every "
            "check, and only the framework's own tree may set it (top-level "
            "modules, `kernel_package: sandloom`, and the running kernel itself "
            "as `sandloom` under `modules_path`)",
            where=str(path),
            fix="delete `kernel_package` and `framework_packages` from the "
            f"manifest of an application{elsewhere}; see docs/operate/upgrade.md",
        )
    )


def _refuse_kernel_in_api_lists(
    path: Path, shared_api: set[str], test_api: set[str]
) -> None:
    for key, entries in (("shared_api", shared_api), ("test_api", test_api)):
        beyond = sorted(e for e in entries if _covers_core_beyond_test_surface(e))
        if beyond:
            raise ManifestError(
                error_codes.render(
                    CORE_IN_API_LIST_CODE,
                    f"`{key}` lists the kernel, which a module's tests would "
                    f"then import: {', '.join(beyond)}",
                    where=str(path),
                    fix=f"delete {', '.join(beyond)} from `{key}` (tests keep "
                    "`sandloom.core.testing` and `sandloom.core.contract_testing` "
                    "by default; `sandloom.sdk.testing` is the rest); "
                    "see docs/operate/upgrade.md",
                )
            )


def _checked_allowlist(
    path: Path, raw: Any, modules_rel: str, *, framework_tree: bool
) -> list[dict[str, Any]]:
    """The ``allowlist`` entries, each a ``file`` glob and a list of ``imports``
    globs. An application's entry admits no kernel module at all; in the
    framework tree an entry that admits the kernel must name specific imports
    and the files of one business module (SANDLOOM-C042)."""
    if not isinstance(raw, list):
        raise ManifestError("`allowlist` must be a list")
    entries: list[dict[str, Any]] = []
    too_wide: list[str] = []
    for index, entry in enumerate(raw):
        if not (
            isinstance(entry, dict)
            and isinstance(entry.get("file"), str)
            and entry["file"]
            and isinstance(entry.get("imports"), list)
            and all(isinstance(i, str) for i in entry["imports"])
        ):
            raise ManifestError(
                f"`allowlist` entry {index} needs a `file` glob and a list of "
                f"`imports` globs: {entry!r}"
            )
        kernel = [p for p in entry["imports"] if _admits_kernel(p)[0]]
        if kernel and (
            not framework_tree
            or any(_admits_kernel(p)[1] for p in kernel)
            or not _names_one_module(entry["file"], modules_rel)
        ):
            too_wide.append(f"file {entry['file']!r} admits {', '.join(kernel)}")
        entries.append(entry)
    if too_wide:
        what, fix = _allowlist_refusal(too_wide, modules_rel, framework_tree)
        raise ManifestError(
            error_codes.render(CORE_IN_ALLOWLIST_CODE, what, where=str(path), fix=fix)
        )
    return entries


def _allowlist_refusal(
    too_wide: list[str], modules_rel: str, framework_tree: bool
) -> tuple[str, str]:
    """``(message, fix)`` of a C042 refusal: an application may excuse no kernel
    module; the framework tree one module's named imports."""
    if framework_tree:
        return (
            "`allowlist` admits the kernel for more than the named modules "
            f"of one business module: {'; '.join(too_wide)}",
            "list the specific `sandloom.core.<module>` imports one "
            "business module still keeps, under a `file` of that module "
            f"(`{modules_rel or '.'}/<module>/...`), or move the import to "
            "`sandloom.sdk`; see docs/operate/upgrade.md",
        )
    return (
        "`allowlist` excuses a kernel import, which an application's manifest "
        f"may not do for any file: {'; '.join(too_wide)}",
        "move the import to `sandloom.sdk` and delete the entry (the allowlist "
        "keeps imports of other packages); see docs/operate/upgrade.md",
    )


def _yaml() -> Any:
    try:
        return importlib.import_module("yaml")
    except ImportError as exc:
        raise ManifestError(
            "reading architecture_rules.yml needs PyYAML, which is not "
            "installed. Install the framework's `check` extra:\n"
            '    pip install "sandloom[check]"   '
            '(or: uv pip install "sandloom[check]")\n'
            "(`sandloom new` projects get it via their `dev` extra)"
        ) from exc


def load_rules(path: Path) -> ArchRules:  # noqa: C901
    """Parse a manifest file into :class:`ArchRules`."""
    path = path.resolve()
    if not path.is_file():
        raise ManifestError(f"manifest not found: {path}")
    raw = _yaml().safe_load(path.read_text(encoding="utf-8"))
    if raw is not None and not isinstance(raw, dict):
        raise ManifestError(f"{path}: top level must be a mapping")
    data = cast("dict[str, Any]", raw or {})
    root = path.parent

    modules_rel = data.get("modules_path")
    if not modules_rel:
        raise ManifestError(
            f"{path}: `modules_path` (directory of business modules) is required"
        )
    modules_path = (root / str(modules_rel)).resolve()
    if not modules_path.is_dir():
        raise ManifestError(f"`modules_path` is not a directory: {modules_path}")
    source_root = (root / str(data.get("source_root") or ".")).resolve()

    modules_package = data.get("modules_package")
    if modules_package is None:
        try:
            rel = modules_path.relative_to(source_root)
        except ValueError as exc:
            raise ManifestError(
                f"{path}: `modules_path` is not under `source_root`; set "
                "`modules_package` explicitly"
            ) from exc
        modules_package = ".".join(rel.parts)

    public_api = set(_str_list(data, "public_api"))
    shared_api = set(_str_list(data, "shared_api"))
    if "allowed_framework_imports" in data:
        raise ManifestError(
            f"{path}: `allowed_framework_imports` is no longer read; list "
            "`sandloom.sdk` modules under `public_api` and the rest under "
            "`shared_api`"
        )
    core_entries = sorted(e for e in public_api if _covers_core(e))
    if core_entries:
        raise ManifestError(
            error_codes.render(
                CORE_IN_PUBLIC_API_CODE,
                "`public_api` lists the kernel, which a business module no "
                f"longer imports: {', '.join(core_entries)}",
                where=str(path),
                fix=f"delete {', '.join(core_entries)} from `public_api` "
                "(`sandloom.sdk` is the public surface); "
                "see docs/operate/upgrade.md",
            )
        )
    kernel = str(data["kernel_package"]) if data.get("kernel_package") else None
    framework_packages = set(_str_list(data, "framework_packages"))
    framework_tree = _is_framework_tree(modules_path, str(modules_package), kernel)
    _refuse_kernel_exemptions(
        path,
        framework_tree=framework_tree,
        kernel=kernel,
        framework=framework_packages,
        elsewhere=_kernel_elsewhere_hint(modules_path, str(modules_package), kernel),
    )
    test_api = set(_str_list(data, "test_api"))
    _refuse_kernel_in_api_lists(path, shared_api, test_api)
    if not public_api:
        public_api = set(DEFAULT_PUBLIC_API)
    if not shared_api:
        shared_api = set(DEFAULT_SHARED_API)
    test_api = test_api or set(DEFAULT_TEST_API)
    try:
        modules_rel = modules_path.relative_to(root).as_posix()
    except ValueError:
        modules_rel = modules_path.as_posix()
    allowlist = _checked_allowlist(
        path, data.get("allowlist") or [], modules_rel, framework_tree=framework_tree
    )

    layers_any = cast("dict[str, Any]", data.get("layers") or {})
    defs: dict[str, set[str]] = {}
    for layer in cast("list[dict[str, Any]]", layers_any.get("definitions") or []):
        name = layer.get("name")
        if name:
            defs[str(name)] = {str(i) for i in layer.get("includes") or []}
    layer_rules: list[tuple[str, set[str]]] = []
    for r in cast("list[dict[str, Any]]", layers_any.get("rules") or []):
        frm = r.get("from")
        if frm:
            layer_rules.append((str(frm), {str(t) for t in r.get("to") or []}))

    exempt: dict[str, str] = {}
    raw_exempt = data.get("tenant_scope_exempt") or []
    if not isinstance(raw_exempt, list):
        raise ManifestError("`tenant_scope_exempt` must be a list")
    for entry in raw_exempt:
        table = entry.get("table") if isinstance(entry, dict) else None
        reason = entry.get("reason") if isinstance(entry, dict) else None
        if not table or not str(reason or "").strip():
            raise ManifestError(
                "`tenant_scope_exempt` entries need both `table` and a written "
                f"`reason`: {entry!r}"
            )
        exempt[str(table)] = str(reason).strip()

    return ArchRules(
        root=root,
        modules_path=modules_path,
        modules_package=str(modules_package),
        source_root=source_root,
        kernel_package=kernel,
        exclude_modules=set(_str_list(data, "exclude_modules")),
        framework_packages=framework_packages,
        public_api=public_api,
        shared_api=shared_api,
        test_api=test_api,
        forbidden_patterns=[
            *dict.fromkeys(
                (
                    *DEFAULT_FORBIDDEN_PATTERNS,
                    *_str_list(data, "forbidden_patterns"),
                )
            )
        ],
        allowlist=allowlist,
        layers_enabled=bool(layers_any.get("enabled", False)),
        layers_defs=defs,
        layer_rules=layer_rules,
        tenant_scope_exempt=exempt,
        shared_package=str(data["shared_package"])
        if data.get("shared_package")
        else None,
    )


