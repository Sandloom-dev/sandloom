"""``architecture_rules.yml`` — the import-boundary manifest ``sandloom check`` reads.

One schema serves the framework tree (``architecture_rules.yml``) and an
application generated by ``sandloom new``. Keys (paths are relative to the manifest):

``modules_path``     directory holding the business-module packages
                     (framework: ``src/sandloom``; app: ``<app>/modules``)
``modules_package``  dotted package of that directory (``<app>.modules``);
                     default derived from ``modules_path`` relative to
                     ``source_root``. Empty (``""``, ``modules_path`` equal to
                     ``source_root``): the modules are top-level packages —
                     the framework tree (``sandloom_identity``, ...) and any
                     repository of ecosystem module packages
``source_root``      the ``sys.path`` root the packages are importable from
                     (framework: ``src``; app: ``.``) — used to resolve relative
                     imports
``kernel_package``   optional package under ``modules_path`` that is the kernel
                     (framework: ``sandloom``): only layer-checked, never a
                     module
``exclude_modules``  packages under ``modules_path`` that are not business modules
``framework_packages`` packages under ``modules_path`` that are framework code
                     above the kernel (framework: ``sdk``, Public API 1.0):
                     never a module and not import-checked as one; their
                     boundaries are import-linter contracts
``public_api``       ``sandloom.core.*`` modules a business module may import
``shared_api``       further framework prefixes a module may import
                     (default ``[sandloom.shared]``)
``test_api``         framework test surfaces a module's TESTS may import on top
                     of ``public_api`` + ``shared_api`` + the module's own
                     package (default ``[sandloom.core.testing,
                     sandloom.core.contract_testing]``)
``forbidden_patterns`` / ``allowlist`` / ``layers``  as documented in the
                     framework manifest.
``shared_package``   the contract-DTO package that receives the generated
                     contract stubs (``<pkg>/contracts/``) and the exported
                     producer event schemas (``<pkg>/events/``), Public API
                     1.0 spec §5.2, §5.3 (default: ``sandloom.shared`` in the
                     framework tree, ``<app>.shared`` in an application)
``tenant_scope_exempt`` tables with a tenant-like column (``tenant_id``,
                     ``organization_id``, ...) that deliberately do
                     not inherit ``TenantScoped`` (rule
                     ``tenant-scoped-models``): a list of
                     ``{table: <name>, reason: <why>}``; both keys are
                     required, and an entry matching no such table fails the
                     check (stale).

The former key ``allowed_framework_imports`` is refused (split it into
``public_api`` and ``shared_api``).
"""

from __future__ import annotations

import importlib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, cast

#: The framework's ENFORCED public import contract for business modules. Used
#: when a manifest names none (and mirrored by architecture_rules.yml).
DEFAULT_PUBLIC_API: tuple[str, ...] = (
    "sandloom.core.di",
    "sandloom.core.facade",
    "sandloom.core.module_api",
    "sandloom.core.descriptors",
    "sandloom.core.orm",
    "sandloom.core.projections",
)
DEFAULT_SHARED_API: tuple[str, ...] = ("sandloom.shared",)
DEFAULT_TEST_API: tuple[str, ...] = (
    "sandloom.core.testing",
    "sandloom.core.contract_testing",
)


class ManifestError(ValueError):
    """The manifest is missing, unreadable or inconsistent."""


@dataclass
class ArchRules:
    root: Path
    modules_path: Path
    modules_package: str
    source_root: Path
    kernel_package: str | None = None
    exclude_modules: set[str] = field(default_factory=set)
    framework_packages: set[str] = field(default_factory=set)
    public_api: set[str] = field(default_factory=lambda: set(DEFAULT_PUBLIC_API))
    shared_api: set[str] = field(default_factory=lambda: set(DEFAULT_SHARED_API))
    test_api: set[str] = field(default_factory=lambda: set(DEFAULT_TEST_API))
    forbidden_patterns: list[str] = field(default_factory=list)
    allowlist: list[dict[str, Any]] = field(default_factory=list)
    layers_enabled: bool = False
    layers_defs: dict[str, set[str]] = field(default_factory=dict)
    layer_rules: list[tuple[str, set[str]]] = field(default_factory=list)
    #: ``table -> reason`` exempt from the ``tenant-scoped-models`` rule.
    tenant_scope_exempt: dict[str, str] = field(default_factory=dict)
    #: The contract-DTO package of generated stubs and exported event schemas.
    shared_package: str | None = None

    @property
    def top_level_modules(self) -> bool:
        """The business modules are top-level packages (``modules_package``
        empty): the framework tree or an ecosystem module repository."""
        return not self.modules_package

    def module_package(self, module: str) -> str:
        """The import path of business module ``module`` (a directory name)."""
        return f"{self.modules_package}.{module}" if self.modules_package else module

    @property
    def shared_dto_package(self) -> str:
        """``shared_package``, else ``sandloom.shared`` (framework tree) /
        ``<app>.shared``."""
        if self.shared_package:
            return self.shared_package
        if self.is_framework_tree:
            return "sandloom.shared"
        top = self.modules_package.split(".")[0]
        if not top:
            raise ManifestError(
                "top-level module packages need `shared_package` (the contract "
                "DTO package of generated stubs) in architecture_rules.yml"
            )
        return f"{top}.shared"

    @property
    def shared_dir(self) -> Path:
        """The directory of :attr:`shared_dto_package` under ``source_root``."""
        return self.source_root.joinpath(*self.shared_dto_package.split("."))

    @property
    def is_framework_tree(self) -> bool:
        """The framework checkout: its kernel is the ``sandloom`` package and
        its modules are the top-level ecosystem packages next to it."""
        return self.top_level_modules and self.kernel_package == "sandloom"

    @property
    def model_roots(self) -> tuple[str, ...]:
        """Top-level packages whose ``.models`` count as ORM in endpoint files."""
        if self.top_level_modules:
            return ("sandloom", *self.business_modules())
        return ("sandloom", self.modules_package.split(".")[0])

    def business_modules(self) -> list[str]:
        excluded = set(self.exclude_modules) | self.framework_packages
        if self.kernel_package:
            excluded.add(self.kernel_package)
        if not self.modules_path.is_dir():
            raise ManifestError(
                f"`modules_path` is not a directory: {self.modules_path}"
            )
        return sorted(
            d.name
            for d in self.modules_path.iterdir()
            if d.is_dir()
            and (d / "__init__.py").exists()
            and not d.name.startswith(("_", "."))
            and d.name not in excluded
        )


def _str_list(data: dict[str, Any], key: str) -> list[str]:
    value = data.get(key) or []
    if not isinstance(value, list):
        raise ManifestError(f"`{key}` must be a list")
    return [str(v) for v in value]


def _yaml() -> Any:
    try:
        return importlib.import_module("yaml")
    except ImportError as exc:
        raise ManifestError(
            "reading architecture_rules.yml needs PyYAML, which is not "
            "installed. Install the framework's `check` extra:\n"
            '    pip install "sandloom[check]"   '
            '(or: uv pip install "sandloom[check]")\n'
            "(`sandloom new` projects get it via their `dev` extra)"
        ) from exc


def load_rules(path: Path) -> ArchRules:  # noqa: C901
    """Parse a manifest file into :class:`ArchRules`."""
    path = path.resolve()
    if not path.is_file():
        raise ManifestError(f"manifest not found: {path}")
    raw = _yaml().safe_load(path.read_text(encoding="utf-8"))
    if raw is not None and not isinstance(raw, dict):
        raise ManifestError(f"{path}: top level must be a mapping")
    data = cast("dict[str, Any]", raw or {})
    root = path.parent

    modules_rel = data.get("modules_path")
    if not modules_rel:
        raise ManifestError(
            f"{path}: `modules_path` (directory of business modules) is required"
        )
    modules_path = (root / str(modules_rel)).resolve()
    if not modules_path.is_dir():
        raise ManifestError(f"`modules_path` is not a directory: {modules_path}")
    source_root = (root / str(data.get("source_root") or ".")).resolve()

    modules_package = data.get("modules_package")
    if modules_package is None:
        try:
            rel = modules_path.relative_to(source_root)
        except ValueError as exc:
            raise ManifestError(
                f"{path}: `modules_path` is not under `source_root`; set "
                "`modules_package` explicitly"
            ) from exc
        modules_package = ".".join(rel.parts)

    public_api = set(_str_list(data, "public_api"))
    shared_api = set(_str_list(data, "shared_api"))
    if "allowed_framework_imports" in data:
        raise ManifestError(
            f"{path}: `allowed_framework_imports` is no longer read; list "
            "`sandloom.core.*` entries under `public_api` and the rest under "
            "`shared_api`"
        )
    if not public_api:
        public_api = set(DEFAULT_PUBLIC_API)
    if not shared_api:
        shared_api = set(DEFAULT_SHARED_API)
    test_api = set(_str_list(data, "test_api")) or set(DEFAULT_TEST_API)

    layers_any = cast("dict[str, Any]", data.get("layers") or {})
    defs: dict[str, set[str]] = {}
    for layer in cast("list[dict[str, Any]]", layers_any.get("definitions") or []):
        name = layer.get("name")
        if name:
            defs[str(name)] = {str(i) for i in layer.get("includes") or []}
    layer_rules: list[tuple[str, set[str]]] = []
    for r in cast("list[dict[str, Any]]", layers_any.get("rules") or []):
        frm = r.get("from")
        if frm:
            layer_rules.append((str(frm), {str(t) for t in r.get("to") or []}))

    exempt: dict[str, str] = {}
    raw_exempt = data.get("tenant_scope_exempt") or []
    if not isinstance(raw_exempt, list):
        raise ManifestError("`tenant_scope_exempt` must be a list")
    for entry in raw_exempt:
        table = entry.get("table") if isinstance(entry, dict) else None
        reason = entry.get("reason") if isinstance(entry, dict) else None
        if not table or not str(reason or "").strip():
            raise ManifestError(
                "`tenant_scope_exempt` entries need both `table` and a written "
                f"`reason`: {entry!r}"
            )
        exempt[str(table)] = str(reason).strip()

    kernel = data.get("kernel_package")
    return ArchRules(
        root=root,
        modules_path=modules_path,
        modules_package=str(modules_package),
        source_root=source_root,
        kernel_package=str(kernel) if kernel else None,
        exclude_modules=set(_str_list(data, "exclude_modules")),
        framework_packages=set(_str_list(data, "framework_packages")),
        public_api=public_api,
        shared_api=shared_api,
        test_api=test_api,
        forbidden_patterns=_str_list(data, "forbidden_patterns"),
        allowlist=list(cast("list[dict[str, Any]]", data.get("allowlist") or [])),
        layers_enabled=bool(layers_any.get("enabled", False)),
        layers_defs=defs,
        layer_rules=layer_rules,
        tenant_scope_exempt=exempt,
        shared_package=str(data["shared_package"])
        if data.get("shared_package")
        else None,
    )


