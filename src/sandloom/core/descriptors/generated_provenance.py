"""What makes a file in a module's reserved ``_generated/`` package generated.

Pure data and string functions, importable without settings: ``sandloom
generate`` (:mod:`sandloom.core.cli.consumer_copies`) writes and verifies the
files with them, and ``sandloom check`` (SANDLOOM-C032) refuses a file in
``<module>/_generated/`` that none of them recognises (ADR-0013 decisions 1
and 7):

- a Python copy (stub, DTO copies) starts with the provenance header, whose
  digest covers the body;
- a package ``__init__.py`` is exactly :data:`INIT`;
- an expectation (``<stem>.describe.json``) carries a ``digest`` of its
  canonical content, so a hand edit is found without the provider too.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping
from typing import Any

__all__ = [
    "EXPECTATION_DIGEST",
    "EXPECTATION_SUFFIX",
    "FIRST_LINE",
    "GENERATED",
    "INIT",
    "digest",
    "is_generated",
    "read_header",
    "signed_expectation",
    "verify",
    "verify_expectation",
]

#: The reserved subpackage of a module distribution (``<module>/_generated/``).
GENERATED = "_generated"
EXPECTATION_SUFFIX = ".describe.json"
#: The key of an expectation's own digest.
EXPECTATION_DIGEST = "digest"
FIRST_LINE = "# Generated by `sandloom generate`: never edit by hand."
INIT = '"""Generated consumer copies (`sandloom generate`): never edit by hand."""\n'


def digest(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()[:16]


def read_header(text: str) -> tuple[dict[str, str], str]:
    """``({key: value}, body)`` of a file under the provenance header
    (``format`` and ``digest`` from its generator line)."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].rstrip("\n") != FIRST_LINE:
        return {}, text
    meta: dict[str, str] = {}
    index = 1
    while index < len(lines) and lines[index].startswith("# "):
        for part in lines[index][2:].rstrip("\n").split("  "):
            key, sep, value = part.partition(": ")
            if key == "generator" and sep:
                key, _, value = value.partition(" ")
            elif not sep:
                key, _, value = part.partition(" ")
            key, value = key.strip(), value.strip()
            meta[key] = f"{meta[key]}, {value}" if key in meta else value
        index += 1
    return meta, "".join(lines[index:])


def verify(text: str) -> str | None:
    """A problem when ``text``'s body does not match its header digest."""
    meta, body = read_header(text)
    found = meta.get("digest")
    if found is None:
        return "no provenance header (digest missing)"
    if found != digest(body):
        return f"hand-edited: digest {found} in the header, {digest(body)} of the body"
    return None


def _canonical(doc: Mapping[str, Any]) -> str:
    body = {k: v for k, v in doc.items() if k != EXPECTATION_DIGEST}
    return json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def signed_expectation(doc: Mapping[str, Any]) -> dict[str, Any]:
    """``doc`` with the digest of its canonical content (every other key)."""
    return {**doc, EXPECTATION_DIGEST: digest(_canonical(doc))}


def verify_expectation(text: str) -> str | None:
    """A problem when an expectation's content does not match its digest."""
    try:
        doc = json.loads(text)
    except json.JSONDecodeError as exc:
        return f"not a JSON document ({exc.msg})"
    if not isinstance(doc, dict) or EXPECTATION_DIGEST not in doc:
        return "no digest (not written by sandloom generate)"
    found, expected = doc[EXPECTATION_DIGEST], digest(_canonical(doc))
    if found != expected:
        return f"hand-edited: digest {found} in the file, {expected} of its content"
    return None


def is_generated(name: str, text: str) -> str | None:
    """``None`` when the file ``name`` (a basename) holding ``text`` was
    written by ``sandloom generate`` and is unchanged, else why not."""
    if name == "__init__.py" and text == INIT:
        return None
    if name.endswith(EXPECTATION_SUFFIX):
        return verify_expectation(text)
    if name.endswith(".py"):
        return verify(text)
    return "not a file sandloom generate writes"
