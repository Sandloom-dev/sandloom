def ruff_formatted(text: str, path: Path, *, cwd: Path | None = None) -> str:
    """``text`` with its imports sorted and formatted by the project's ruff
    (configuration found from ``path``); unchanged without ruff."""
    for argv in (
        ["check", "--select", "I", "--fix", "--quiet", "--exit-zero"],
        ["format", "--quiet"],
    ):
        try:
            proc = _tool_process.run_tool(
                [
                    sys.executable,
                    "-m",
                    "ruff",
                    *argv,
                    "--stdin-filename",
                    str(path),
                    "-",
                ],
                cwd=cwd or Path.cwd(),
                capture=True,
                stdin=text,
            )
        except OSError:
            return text
        if proc.returncode != 0 or not proc.stdout:
            return text
        text = proc.stdout
    return text


