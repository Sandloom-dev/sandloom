class Imports:
    """The imports a generated file needs (isort order is ruff's job)."""

    def __init__(self) -> None:
        self.names: dict[str, set[str]] = {}

    def need(self, module: str, name: str) -> str:
        self.names.setdefault(module, set()).add(name)
        return name

    def render(self) -> str:
        return "\n".join(
            f"from {module} import {', '.join(sorted(names))}"
            for module, names in sorted(self.names.items())
        )


_SIMPLE = {int: "int", str: "str", float: "float", bool: "bool", type(None): "None"}
_FROM = {
    uuid.UUID: ("uuid", "UUID"),
    _dt.datetime: ("datetime", "datetime"),
    _dt.date: ("datetime", "date"),
    _dt.time: ("datetime", "time"),
    _dt.timedelta: ("datetime", "timedelta"),
    decimal.Decimal: ("decimal", "Decimal"),
}
_GENERIC = {
    list: "list",
    dict: "dict",
    tuple: "tuple",
    set: "set",
    frozenset: "frozenset",
}
#: annotated_types constraint -> its ``Field`` keyword.
_CONSTRAINTS: dict[type, str] = {
    annotated_types.Gt: "gt",
    annotated_types.Ge: "ge",
    annotated_types.Lt: "lt",
    annotated_types.Le: "le",
    annotated_types.MultipleOf: "multiple_of",
    annotated_types.MinLen: "min_length",
    annotated_types.MaxLen: "max_length",
}


class Renderer:
    """Python source of annotations, values and constraints."""

    def __init__(self, resolver: Resolver, imports: Imports) -> None:
        self.resolver = resolver
        self.imports = imports

    # -- values ---------------------------------------------------------- #

    def value(self, value: Any, where: str) -> str:
        """Source of a default / Literal value (refused when not writable)."""
        if isinstance(value, list | tuple | set | frozenset | dict):
            return self._container(value, where)
        source = self._scalar(value, where)
        if source is None:
            raise CopyError(
                where,
                f"its default {value!r} ({type(value).__name__}) cannot be written "
                "into the generated copy",
                "use a JSON scalar, an Enum member, a UUID / Decimal / date / "
                "datetime / time / timedelta, or a list / tuple / set / dict of "
                "them (default_factory=list / dict / set / frozenset / tuple)",
            )
        return source

    def _scalar(self, value: Any, where: str) -> str | None:
        if isinstance(value, enum.Enum):
            module, name = self.resolver.place(type(value), where)
            if module != self.resolver.dto_package:
                self.imports.need(module, name)
            return f"{name}.{value.name}"
        if isinstance(value, float) and not math.isfinite(value):
            raise CopyError(
                where, f"default {value!r} is not finite", "use a finite default"
            )
        if value is None or isinstance(value, bool | int | float):
            return repr(value)
        if isinstance(value, str):
            return json.dumps(value, ensure_ascii=False)
        if type(value) not in _FROM:
            return None
        module, name = _FROM[type(value)]
        self.imports.need(module, name)
        if isinstance(value, _dt.timedelta):
            return f"timedelta(seconds={value.total_seconds()!r})"
        if isinstance(value, _dt.date | _dt.time):
            return f"{name}.fromisoformat({json.dumps(value.isoformat())})"
        return f"{name}({json.dumps(str(value))})"  # UUID, Decimal

    def _container(self, value: Any, where: str) -> str:
        if isinstance(value, dict):
            pairs = [
                f"{self.value(k, where)}: {self.value(v, where)}"
                for k, v in value.items()
            ]
            return "{" + ", ".join(pairs) + "}"
        items = [self.value(item, where) for item in value]
        if isinstance(value, list):
            return f"[{', '.join(items)}]"
        if isinstance(value, tuple):
            return f"({items[0]},)" if len(items) == 1 else f"({', '.join(items)})"
        if not items:
            return f"{type(value).__name__}()"
        inner = "{" + ", ".join(sorted(items)) + "}"
        return inner if isinstance(value, set) else f"frozenset({inner})"

    # -- annotations ----------------------------------------------------- #

    def annotation(self, tp: Any, where: str, *, constraints: bool = True) -> str:
        """Source of a wire annotation. ``constraints``: keep ``Annotated``
        metadata (a DTO field); a stub signature drops it."""
        if tp in _SIMPLE:
            return _SIMPLE[tp]
        if tp in _FROM:
            module, name = _FROM[tp]
            return self.imports.need(module, name)
        if tp is typing.Any:
            return self.imports.need("typing", "Any")
        if typing.get_origin(tp) is not None:
            return self._generic(tp, where, constraints)
        if inspect.isclass(tp) and issubclass(tp, enum.Enum | BaseModel):
            module, name = self.resolver.place(tp, where)
            if module == self.resolver.dto_package:
                return name  # defined in the generated module itself
            return self.imports.need(module, name)
        raise CopyError(
            where,
            f"{tp!r} is not a contract wire type the generator can copy",
            contract_wire.annotation_problem(tp) or "use a wire type",
        )

    def _generic(self, tp: Any, where: str, constraints: bool) -> str:
        origin = typing.get_origin(tp)
        args = typing.get_args(tp)
        if origin is typing.Literal:
            self.imports.need("typing", "Literal")
            return f"Literal[{', '.join(self.value(a, where) for a in args)}]"
        inner = [
            "..."
            if a is Ellipsis
            else self.annotation(a, where, constraints=constraints)
            for a in (args[:1] if origin is typing.Annotated else args)
        ]
        if origin is typing.Annotated:
            kwargs = self.metadata(args[1:], where) if constraints else {}
            if not kwargs:
                return inner[0]
            self.imports.need("typing", "Annotated")
            return f"Annotated[{inner[0]}, {self.field_call(kwargs)}]"
        if origin in (typing.Union, types.UnionType):
            return " | ".join(inner)
        if origin in _GENERIC:
            name = _GENERIC[origin]
        elif getattr(origin, "__module__", "") == "collections.abc":
            name = self.imports.need("collections.abc", origin.__name__)
        else:
            raise CopyError(
                where,
                f"{tp!r} is not a contract wire type the generator can copy",
                contract_wire.annotation_problem(tp) or "use a wire type",
            )
        return f"{name}[{', '.join(inner)}]" if inner else name

    # -- constraints ----------------------------------------------------- #

    def metadata(self, items: Iterable[Any], where: str) -> dict[str, str]:
        """``Field`` keywords (name -> source) of ``Annotated`` metadata."""
        out: dict[str, str] = {}
        for item in items:
            out.update(self._constraint(item, where))
        return out

    def _constraint(self, item: Any, where: str) -> dict[str, str]:
        """The ``Field`` keywords of one metadata item (refused when unknown)."""
        if type(item) in _CONSTRAINTS:
            key = _CONSTRAINTS[type(item)]
            return {key: self.value(getattr(item, key), where)}
        if isinstance(item, FieldInfo):
            return self._field_info(item, where)
        if isinstance(item, StringConstraints):
            found = {k: v for k, v in vars(item).items() if v is not None}
            if {"strip_whitespace", "to_upper", "to_lower", "ascii_only"} & set(found):
                raise CopyError(
                    where,
                    "a StringConstraints transformation (strip_whitespace, "
                    "to_upper, to_lower, ascii_only) is not a wire constraint",
                    "normalise the value in the provider; keep the length "
                    "and pattern constraints (Field(max_length=...))",
                )
            return {k: self.value(v, where) for k, v in found.items()}
        kind = type(item).__name__
        if isinstance(item, annotated_types.Interval | annotated_types.Len) or (
            kind == "_PydanticGeneralMetadata"
        ):
            found = {k: v for k, v in vars(item).items() if v is not None}
            return {k: self.value(v, where) for k, v in found.items()}
        if kind in ("Strict", "AllowInfNan"):
            key = "strict" if kind == "Strict" else "allow_inf_nan"
            return {key: self.value(getattr(item, key), where)}
        raise CopyError(
            where,
            f"the constraint {item!r} cannot be copied",
            "use Field(...) constraints: gt / ge / lt / le, "
            "multiple_of, min_length / max_length, pattern, strict, "
            "max_digits / decimal_places, allow_inf_nan",
        )

    def _field_info(self, item: FieldInfo, where: str) -> dict[str, str]:
        """A ``Field(...)`` nested in ``Annotated``: its constraints and its
        discriminator (a tag field name)."""
        out = self.metadata(item.metadata, where)
        if item.discriminator is None:
            return out
        if not isinstance(item.discriminator, str):
            raise CopyError(
                where,
                "a callable discriminator cannot be copied",
                'name a Literal tag field: Field(discriminator="kind")',
            )
        out["discriminator"] = json.dumps(item.discriminator)
        return out

    def field_call(self, kwargs: dict[str, str]) -> str:
        self.imports.need("pydantic", "Field")
        return f"Field({', '.join(f'{k}={v}' for k, v in kwargs.items())})"


