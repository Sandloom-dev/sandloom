#: ``model_config`` keys a copy carries (literal values). Every other key of
#: the closed set describes the JSON schema only or the provider's own code
#: (``alias_generator`` is resolved into each field's ``alias=``).
_CONFIG_COPIED = (
    "title",
    "json_schema_serialization_defaults_required",
    "extra",
    "frozen",
    "populate_by_name",
    "validate_by_name",
    "validate_by_alias",
    "serialize_by_alias",
    "loc_by_alias",
    "str_to_lower",
    "str_to_upper",
    "str_strip_whitespace",
    "str_min_length",
    "str_max_length",
    "strict",
    "validate_assignment",
    "validate_default",
    "revalidate_instances",
    "from_attributes",
    "allow_inf_nan",
    "hide_input_in_errors",
)
_FIELD_ATTRS = ("title", "description", "examples", "deprecated", "exclude")
_FACTORIES = {list: "list", dict: "dict", set: "set", frozenset: "frozenset"}


def _docstring(cls: type, indent: str = "    ") -> str | None:
    doc = cls.__dict__.get("__doc__")
    if not isinstance(doc, str) or not doc.strip():
        return None
    text = inspect.cleandoc(doc).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = text.splitlines()
    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""'
    body = "\n".join(f"{indent}{line}".rstrip() for line in lines[1:])
    return f'{indent}"""{lines[0]}\n{body}\n{indent}"""'


def _render_enum(cls: type[enum.Enum], r: Renderer) -> str:
    where = cls.__qualname__
    if issubclass(cls, enum.Flag):
        raise CopyError(where, "a Flag enum is not a wire type", "use an Enum")
    if issubclass(cls, enum.StrEnum):
        bases = r.imports.need("enum", "StrEnum")
    elif issubclass(cls, enum.IntEnum):
        bases = r.imports.need("enum", "IntEnum")
    else:
        enum_name = r.imports.need("enum", "Enum")
        mixin = (
            "str, " if issubclass(cls, str) else "int, " if issubclass(cls, int) else ""
        )
        bases = f"{mixin}{enum_name}"
    lines = []
    for name, member in cls.__members__.items():
        value = member.value
        if not (value is None or isinstance(value, str | int | float)):
            raise CopyError(
                f"{where}.{name}",
                f"value {value!r} is not a JSON scalar",
                "use str, int, float, bool or None values",
            )
        lines.append(f"    {name} = {r.value(value, where)}")
    doc = _docstring(cls)
    body = "\n".join(lines)
    if doc is not None:
        body = f"{doc}\n\n{body}"
    return f"class {r.resolver.copy_name(cls)}({bases}):\n{body or '    pass'}"


def _render_default(name: str, info: FieldInfo, r: Renderer) -> dict[str, str]:
    where = name
    factory = info.default_factory
    if factory is not None:
        if factory not in _FACTORIES and factory is not tuple:
            raise CopyError(
                where,
                f"default_factory={getattr(factory, '__name__', factory)!r} "
                "cannot be copied",
                "use a literal default, or default_factory=list / dict / set / "
                "frozenset",
            )
        return {"default_factory": "tuple" if factory is tuple else _FACTORIES[factory]}
    if info.default is PydanticUndefined:
        return {}
    return {"default": r.value(info.default, where)}


def _render_field(cls: type[BaseModel], name: str, info: FieldInfo, r: Renderer) -> str:
    where = f"{cls.__qualname__}.{name}"
    if info.exclude_if is not None:
        raise CopyError(
            where, "exclude_if is a callable", "exclude the field always, or never"
        )
    if info.discriminator is not None and not isinstance(info.discriminator, str):
        raise CopyError(
            where,
            "a callable discriminator cannot be copied",
            'name a Literal tag field: Field(discriminator="kind")',
        )
    annotation = r.annotation(info.annotation, where)
    kwargs = _field_kwargs(name, info, r, where)
    if not kwargs:
        return f"    {name}: {annotation}"
    if list(kwargs) == ["default"]:
        return f"    {name}: {annotation} = {kwargs['default']}"
    return f"    {name}: {annotation} = {r.field_call(kwargs)}"


def _field_kwargs(
    name: str, info: FieldInfo, r: Renderer, where: str
) -> dict[str, str]:
    """The ``Field(...)`` keywords of a copied field (name -> source)."""
    kwargs = _render_default(where, info, r)
    if info.alias is not None and info.alias != name:
        kwargs["alias"] = json.dumps(info.alias)
    for attr in ("validation_alias", "serialization_alias"):
        alias = getattr(info, attr)
        if alias is not None and alias != info.alias:
            kwargs[attr] = r.value(alias, where)
    for attr in _FIELD_ATTRS:
        found = getattr(info, attr)
        if found is not None and attr in info._attributes_set:
            kwargs[attr] = r.value(found, where)
    if isinstance(info.json_schema_extra, dict):
        kwargs["json_schema_extra"] = r.value(info.json_schema_extra, where)
    if info.frozen is not None:
        kwargs["frozen"] = repr(info.frozen)
    if info.validate_default is not None:
        kwargs["validate_default"] = repr(info.validate_default)
    if isinstance(info.discriminator, str):
        kwargs["discriminator"] = json.dumps(info.discriminator)
    kwargs.update(r.metadata(info.metadata, where))
    return kwargs


def _render_model(cls: type[BaseModel], r: Renderer) -> str:
    where = cls.__qualname__
    if getattr(cls, "__pydantic_generic_metadata__", {}).get("origin") is not None:
        raise CopyError(
            where,
            "a parametrised generic DTO cannot be copied",
            "declare a concrete model with the item type spelled out",
        )
    config = dict(cls.model_config)
    copied = {k: config[k] for k in _CONFIG_COPIED if k in config}
    lines: list[str] = []
    doc = _docstring(cls)
    if doc is not None:
        lines += [doc, ""]
    if copied:
        r.imports.need("pydantic", "ConfigDict")
        items = ", ".join(f"{k}={r.value(v, where)}" for k, v in copied.items())
        lines += [f"    model_config = ConfigDict({items})", ""]
    lines += [
        _render_field(cls, name, info, r) for name, info in cls.model_fields.items()
    ]
    while lines and lines[-1] == "":
        lines.pop()
    r.imports.need("pydantic", "BaseModel")
    return f"class {r.resolver.copy_name(cls)}(BaseModel):\n" + (
        "\n".join(lines) or "    pass"
    )


def _dependencies(cls: type) -> list[type]:
    if not (inspect.isclass(cls) and issubclass(cls, BaseModel)):
        return []
    out: list[type] = []
    for info in cls.model_fields.values():
        out += contract_wire.nominal_types(info.annotation)
        if isinstance(info.default, enum.Enum):
            out.append(type(info.default))
    return out


def _render_copy(cls: type, renderer: Renderer) -> str:
    if issubclass(cls, enum.Enum):
        return _render_enum(cls, renderer)
    if issubclass(cls, BaseModel):
        return _render_model(cls, renderer)
    raise CopyError(cls.__qualname__, "is not a DTO", "use a model or Enum")


def render_module(module: str, resolver: Resolver) -> str:
    """The generated DTO module of provider module ``module``: a copy of
    every class ``resolver`` placed for copying (and what those name)."""
    imports = Imports()
    r = Renderer(resolver, imports)
    imports.need("sandloom.core.descriptors.contract_refs", "dto_copy")
    # Discover field/default dependencies before choosing any exported name.
    index = 0
    while index < len(resolver.copied):
        _render_copy(resolver.copied[index], r)
        index += 1
    names = [resolver.copy_name(cls) for cls in resolver.copied]
    if len(set(names)) != len(names):
        raise CopyError(
            module, "generated DTO names collide", "rename the conflicting DTO classes"
        )
    blocks = {
        cls: f"@dto_copy({json.dumps(origin_of(cls))})\n{_render_copy(cls, r)}"
        for cls in resolver.copied
    }
    order = _topological(list(blocks))
    position = {cls: i for i, cls in enumerate(order)}
    rebuild = sorted(
        {
            resolver.copy_name(cls)
            for cls in order
            if any(
                dep in position and position[dep] >= position[cls]
                for dep in _dependencies(cls)
            )
        }
    )
    sources = sorted({c.__module__ for c in order})
    head = (
        f'{HEADER}"""Contract DTOs of module ``{module}``: the wire-shape copies '
        "callers import.\n\n"
        "Generated from the provider's own classes in:\n\n"
        + "".join(f"- ``{source}``\n" for source in sources)
        + "\nA copy carries the fields, their types and constraints, defaults,\n"
        "aliases, Literal / Enum values, nested models and model_config options;\n"
        "not the "
        "methods, properties or validators (the provider's own).\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
    )
    text = head + imports.render() + "\n\n\n" + "\n\n\n".join(blocks[c] for c in order)
    text += "\n"
    if rebuild:
        text += "\n\n" + "".join(f"{name}.model_rebuild()\n" for name in rebuild)
    return text


def _topological(classes: list[type]) -> list[type]:
    """Dependencies first (stable); a cycle keeps first-seen order."""
    out: list[type] = []
    visiting: set[type] = set()

    def visit(cls: type) -> None:
        if cls in out or cls in visiting:
            return
        visiting.add(cls)
        for dep in _dependencies(cls):
            if dep in classes:
                visit(dep)
        visiting.discard(cls)
        out.append(cls)

    for cls in classes:
        visit(cls)
    return out


