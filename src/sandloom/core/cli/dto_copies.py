#: The header of every generated DTO module.
HEADER = "# Generated by `sandloom generate` (Public API 1.0): never edit by hand.\n"
CODE = "SANDLOOM-C012"


class CopyError(ValueError):
    """A provider DTO the generator cannot copy faithfully (SANDLOOM-C012)."""

    def __init__(self, where: str, problem: str, fix: str) -> None:
        super().__init__(f"[{CODE}] {where}: {problem}\n  fix: {fix}")
        self.where = where
        self.problem = problem
        self.fix = fix


def dto_module_stem(module: str) -> str:
    """File stem of module ``module``'s generated DTO copies."""
    return f"{module}_dto"


def origin_of(cls: type) -> str:
    """``"<module>:<qualname>"`` of a class (the copy's provenance)."""
    return f"{cls.__module__}:{cls.__qualname__}"


def _within(module: str, package: str) -> bool:
    return module == package or module.startswith(package + ".")


# --------------------------------------------------------------------------- #
# Which classes a signature needs, and where each one lives
# --------------------------------------------------------------------------- #


@dataclass
class Resolver:
    """Decides, per DTO class of a provider module's signatures, whether it
    is referenced (a shared package, an existing generated copy) or copied
    into ``dto_package`` (a class of the provider's own package)."""

    provider_package: str
    dto_package: str
    shared_packages: tuple[str, ...]
    #: the classes to copy, in first-seen order
    copied: list[type] = field(default_factory=list)

    def owned(self, cls: type) -> bool:
        return _within(cls.__module__, self.provider_package)

    def place(self, cls: type, where: str) -> tuple[str, str]:
        """``(module, name)`` a generated file imports ``cls`` from."""
        if copy_origin(cls) is not None or any(
            _within(cls.__module__, p) for p in self.shared_packages
        ):
            return cls.__module__, cls.__name__
        qualname = cls.__qualname__
        if self.owned(cls) and "<locals>" not in qualname and "." not in qualname:
            if cls not in self.copied:
                self.copied.append(cls)
            return self.dto_package, self.copy_name(cls)
        what = (
            "is defined in a function or nested in a class"
            if "." in qualname
            else f"lives in {cls.__module__}, outside the provider's package "
            f"{self.provider_package!r} and every shared DTO package"
        )
        raise CopyError(
            where,
            f"DTO {origin_of(cls)} {what}, so the generator cannot copy it",
            "define the DTO at module level in the provider's own schemas "
            "module; another module's DTO is used through its generated copy "
            "in the shared DTO package",
        )

    def copy_name(self, cls: type) -> str:
        """Keep unique names readable; disambiguate equal names by origin."""
        peers = [other for other in self.copied if other.__name__ == cls.__name__]
        if len(peers) < 2:
            return cls.__name__
        origin = origin_of(cls)
        if any(other is not cls and origin_of(other) == origin for other in peers):
            raise CopyError(
                origin,
                "distinct DTO classes claim the same origin",
                "define each DTO once at a unique module-level path",
            )
        suffix = hashlib.sha256(origin.encode()).hexdigest()[:16]
        return f"{cls.__name__}__{suffix}"

    def collect(self, annotation: Any, where: str) -> None:
        """Place every model / Enum ``annotation`` names (nested included)."""
        for cls in contract_wire.nominal_types(annotation):
            self.place(cls, where)


