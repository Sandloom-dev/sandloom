"""``sandloom check`` — run the framework's architecture rules against an app.

Reads the application's ``architecture_rules.yml`` (generated by ``sandloom new``;
the framework's own lives in ``backend/``) and runs every analyzer of
:mod:`sandloom.core.archcheck` over its business modules:

    module-boundaries      no sibling-module imports (any spelling)
    framework-imports      only the public API (sandloom.core.{di,facade,module_api,
                           descriptors,orm,projections}) + sandloom.shared.*
    raw-provider           no raw_client()/raw_backend()/raw() escape hatches
    unsafe-tenant-sql      raw SQL/Core tables need explicit unscoped() admission
    tenant-scoped-models   a model / Table with a tenant-like column
                           (tenant_id, organization_id, org_id, workspace_id)
                           inherits TenantScoped (or is listed under
                           tenant_scope_exempt + reason)
    infra-imports          no infra internals, legacy globals or backend SDKs
    kernel-handles         no core.event_bus / .infra / .service_registry /
                           app.state.core (kernel handles by attribute)
    uow-boundary           no db.commit()/db.rollback() in module code
    best-effort-effects    publish_event / record_audit(required=False) only
                           with a `# sandloom: best-effort <reason>` marker
    get-core-await         direct get_core(request) calls are awaited
    endpoints-outside-api  HTTP endpoints only under api/ (routers/, ...)
    orm-leakage            no ORM models / SQLAlchemy in endpoint files
    schema-orm-imports     schemas/ stay persistence-free
    contract-dtos          contract signatures use DTOs from sandloom.shared (or
                           CONTRACT_DTO_PACKAGES), never the module's own
    test-imports           module tests import only the public API,
                           sandloom.shared, sandloom.core.testing / contract_testing
                           and their own package
    event-schema-channels  publish_event channels are declared by the module
                           (an Event class, or its events schema map)
    guard-order            idempotency_guard / tenant-dependent gates come
                           after the auth / TenantScope() they need
    consumed-contracts     get_service literals are declared in consumes=
    db-dependency-scope    Depends(get_db...) carries scope="function"

  Public API 1.0 (spec Appendix A; each joins the list above once its code
  is no longer planned in the catalogue; warnings and notes never fail):
    module-local-imports   no function-local import in a module (warning
                           until the bundled modules are clean)
    untagged-sensitive     (warning) a money / credential effect or a
                           hand-rolled authority route without a risk tag
    multi-store-waivers    (info) every allow_multi_db_write, with reason
    unsafe-tenant-query    raw non-relational queries only under unscoped()
    event-view-compat      event views match their producer; views never
                           publish
    contract-union-hint    (info) an ambiguous union uses codec 1
    account-route-mismatch an organization route gates billing with
                           of=Account.user() and no reason

Each violation prints as ``path:N: error[SANDLOOM-Cnnn rule]: message``;
``sandloom explain <code>`` has the long form. A deliberate exception is waived
on its line with ``# sandloom: allow <rule-id> <reason>``.

``--boot`` additionally builds the application (``SANDLOOM_COMPOSITION_ROOT``,
default ``sandloom.main``) through ``create_app`` — no server, no I/O — and reports
every startup refusal (module load failures SANDLOOM-B001, ``GuardOrderError``
SANDLOOM-B002, ``ContractBindingError`` SANDLOOM-B005, registration errors
SANDLOOM-B006,
``GateOrderError`` SANDLOOM-B007, ``RoutePolicyError`` SANDLOOM-B008,
``CapabilityReplayError`` SANDLOOM-B019) and stale route snapshots (SANDLOOM-T001) in
the
same format. It needs the deployment's
configuration (an app's ``.env``; the framework tree: the test env).

Usage::

    sandloom check                                   # ./architecture_rules.yml
    sandloom check --boot                            # + the startup refusals
    sandloom check --rules path/to/architecture_rules.yml
    sandloom check --only module-boundaries,orm-leakage
    sandloom check --list-rules

Exit status: 0 clean, 1 violations, 2 bad manifest / usage. Without
``--boot`` it is purely static: it imports no application code and needs no
environment (no DATABASE_URL).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from sandloom.core import error_codes
from sandloom.core.archcheck.manifest import ArchRules, ManifestError, load_rules
from sandloom.core.archcheck.runner import PENDING_RULES, RULES, Violation, run_checks


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="sandloom check",
        description="Run Sandloom architecture (module isolation) checks",
    )
    parser.add_argument(
        "--rules",
        type=Path,
        default=Path("architecture_rules.yml"),
        help="manifest path (default: ./architecture_rules.yml)",
    )
    parser.add_argument(
        "--only",
        default="",
        help="comma-separated subset of rules to run (default: all)",
    )
    parser.add_argument(
        "--list-rules", action="store_true", help="print the rule ids and exit"
    )
    parser.add_argument(
        "--boot",
        action="store_true",
        help="also build the app through create_app and report startup "
        "refusals and stale route snapshots",
    )
    args = parser.parse_args(argv)

    if args.list_rules:
        for rule, why in RULES.items():
            entry = error_codes.lookup(rule)
            print(f"{entry.code if entry else '':9} {rule:24} {why}")
        return 0

    only = [r.strip() for r in args.only.split(",") if r.strip()] or None
    try:
        rules = load_rules(args.rules)
        violations = run_checks(rules, only=only)
    except (ManifestError, ValueError) as exc:
        print(f"sandloom check: {exc}", file=sys.stderr)
        return 2

    boot = boot_diagnostics() if args.boot else []
    return _report(rules, violations, boot, boot_requested=bool(args.boot))


def _report(
    rules: ArchRules,
    violations: list[Violation],
    boot: list[str],
    *,
    boot_requested: bool,
) -> int:
    """Print warnings / notes, then errors with their fixes; the exit code."""
    modules = rules.business_modules()
    errors = [v for v in violations if v.severity == "error"]
    notes = [v for v in violations if v.severity != "error"]
    if notes:
        print(f"sandloom check: {len(notes)} warning(s) / note(s)\n")
        for v in notes:
            print(f"  {v.format(rules.root)}")
        print()
    if not errors and not boot:
        print(
            f"sandloom check: OK ({len(modules)} module(s) under "
            f"{rules.modules_package or 'the top level'}: "
            f"{', '.join(modules) or '-'}"
            f"{'; boot clean' if boot_requested else ''})"
        )
        return 0
    if not errors:
        _print_boot(boot)
        return 1

    print(f"sandloom check: {len(errors)} architecture violation(s)\n")
    seen: set[str] = set()
    for v in errors:
        print(f"  {v.format(rules.root)}")
        seen.add(v.rule)
    print("\nHow to fix:")
    known = {**RULES, **PENDING_RULES}
    for rule in sorted(seen):
        entry = error_codes.lookup(rule)
        if entry is None:
            print(f"  {rule}: {known[rule]}")
            continue
        print(f"  {entry.code} {rule}: {known[rule]}")
        print(f"      docs: sandloom explain {entry.code}")
    _print_boot(boot)
    return 1


#: Exceptions a startup refusal raises (every create_app refusal is one of
#: them; ConfigurationError is a SystemExit).
_BOOT_REFUSALS = (RuntimeError, ValueError, TypeError, ImportError, SystemExit)


def _print_boot(diagnostics: list[str]) -> None:
    if not diagnostics:
        return
    print(f"\nsandloom check --boot: {len(diagnostics)} startup problem(s)\n")
    for text in diagnostics:
        print(text + "\n")


def boot_diagnostics(root: str | None = None) -> list[str]:
    """Build the app through ``create_app``; render every startup problem.

    No server and no I/O: module loading, route validation and the boot
    checks run, the lifespan does not.
    """
    from sandloom.core.composition import load_composition_app  # noqa: PLC0415 - cold: --boot builds the app; plain `sandloom check` stays static

    try:
        app = load_composition_app(root)
    except _BOOT_REFUSALS as exc:
        message = str(exc) or type(exc).__name__
        code = error_codes.code_for_exception(exc)
        if code is None and message.startswith("[core.config]"):
            return [
                f"error: {message}\n  fix: configure the deployment (.env), or "
                "for the framework tree export the test env (.env.test / "
                "SANDLOOM_TEST_*; docs/guides/testing.md)"
            ]
        return [
            error_codes.render(
                code or "SANDLOOM-B001", f"{type(exc).__name__}: {message}"
            )
        ]
    return _route_diagnostics(app)


def _route_diagnostics(app: object) -> list[str]:
    from sandloom.core import route_snapshots  # noqa: PLC0415 - cold: --boot builds the app; plain `sandloom check` stays static

    out = [
        error_codes.render("SANDLOOM-T001", problem)
        for problem in route_snapshots.snapshot_problems(app)
    ]
    summary = getattr(getattr(app, "state", None), "module_summary", None)
    out += [
        error_codes.render(
            "SANDLOOM-B001",
            f"optional module {failed.name} did not load: {failed.error}",
            severity="warning",
        )
        for failed in getattr(summary, "failed", []) or []
    ]
    return out


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
