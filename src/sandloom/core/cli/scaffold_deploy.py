def _template(project: Project, rel: str) -> str:
    # A template with @@TOKENS@@ is not valid YAML until rendered: `.tmpl`.
    source = TEMPLATES / rel
    if not source.is_file():
        source = TEMPLATES / f"{rel}.tmpl"
    text = source.read_text(encoding="utf-8")
    app_env = "".join(f"{_I}{k}: {v}\n" for k, v in project.app_env)
    return (
        text.replace("@@TITLE@@", project.title)
        .replace("@@BUILD_CONTEXT@@", project.build_context)
        .replace("@@IMAGE@@", project.image)
        .replace(
            "@@DOCKERFILE@@",
            "deploy/docker/Dockerfile" if project.framework else "Dockerfile",
        )
        .replace("@@PORT@@", str(project.port))
        .replace("@@APP_ENV@@", app_env)
    )


def init_files(project: Project) -> list[Path]:
    """Write the profile, gateway and init script the deploy dir lacks."""
    created: list[Path] = []
    for rel in (PROFILE, "gateway/nginx.conf", "postgres/init-databases.sh"):
        path = project.deploy_dir / rel
        if path.exists():
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_template(project, rel), encoding="utf-8")
        if path.suffix == ".sh":
            path.chmod(0o755)
        created.append(path)
    return created


@dataclass
class Result:
    written: list[Path] = field(default_factory=list)
    created: list[Path] = field(default_factory=list)
    services: list[Service] = field(default_factory=list)
    unresolved: list[str] = field(default_factory=list)
    refusals: list[str] = field(default_factory=list)


def deploy(
    project: Project,
    modules: list[str] | None = None,
    service: str | None = None,
    *,
    force: bool = False,
) -> Result:
    """Put ``modules`` in ``service`` (none: re-derive only) and rewrite the
    generated blocks of the profile and the gateway."""
    result = Result()
    compose_path = project.deploy_dir / PROFILE
    nginx_path = project.deploy_dir / "gateway" / "nginx.conf"
    text = _open_profile(project, compose_path, nginx_path, bool(modules), result)
    services = read_services(text)
    if modules:
        _place(services, [project.dotted(m) for m in modules], service)
    for svc in services:
        svc.topology = _dp.service_topology(svc.modules)
        if svc.topology.error:
            raise DeployError(
                f"service {svc.name!r} ({', '.join(svc.modules)}) does not load: "
                f"{svc.topology.error}"
            )
    compose, gateway, result.unresolved = render(project, services)
    result.services = services
    nginx = nginx_path.read_text(encoding="utf-8")
    _refuse_static_fallback(nginx, nginx_path)
    new_compose, refused = apply_regions(
        text, compose, force=force, where=str(compose_path)
    )
    new_nginx, refused_nginx = apply_regions(
        nginx, gateway, force=force, where=str(nginx_path)
    )
    result.refusals = refused + refused_nginx
    if result.refusals and not force:
        return result
    for path, old, new in (
        (compose_path, text, new_compose),
        (nginx_path, nginx, new_nginx),
    ):
        if new != old:
            path.write_text(new, encoding="utf-8")
            if path not in result.created:
                result.written.append(path)
    # The dev keys (`sandloom keys dev-env --out deploy/.env.microservices`) live
    # in an app's build context: its .dockerignore must keep them, and every
    # key file, out of the image at any depth.
    if not project.framework and _image_secrets.patch_dockerignore(project.root):
        result.written.append(project.root / ".dockerignore")
    return result


def _refuse_static_fallback(nginx: str, path: Path) -> None:
    """The catch-all ``location /`` is generated (the 404, or the service
    serving root-level routes): one outside the routes block would make
    nginx refuse a duplicate location."""
    outside = _REGION.sub("", nginx)
    if re.search(r"^\s*location\s+/\s*\{", outside, re.M):
        raise DeployError(
            f"{path}: `location / {{ ... }}` outside the generated routes "
            "block: the catch-all is generated now (the edge's 404, or the "
            "service serving root-level routes). Delete that line and run "
            "`sandloom add deploy --refresh` (SANDLOOM-T014)"
        )


def _open_profile(
    project: Project, compose: Path, nginx: Path, adding: bool, result: Result
) -> str:
    """The profile's text; the files the deploy dir lacks are created first
    (the first ``sandloom add deploy``)."""
    if not compose.is_file() and not adding:
        raise DeployError(
            f"no {compose}: `sandloom add deploy <module>... "
            f"--service <name>` creates it"
        )
    if not compose.is_file() or not nginx.is_file():
        result.created = init_files(project)
    text = compose.read_text(encoding="utf-8")
    if "service-env" not in regions(text):
        raise DeployError(
            f"{compose} has no `{_BEGIN}service-env` block: it was not "
            "created by `sandloom add deploy`. Move it aside and run the command "
            "again to create a generated profile (then carry your edits over, "
            "outside the generated blocks)"
        )
    return text


def _service_name(dotted: list[str], name: str | None) -> str:
    if name is None:
        if len(dotted) != 1:
            raise DeployError("several modules need --service <name>")
        name = _module_name(dotted[0])
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
        raise DeployError("the service name must be snake_case")
    if name in {"gateway", "db", "redis"} or name.startswith("migrate"):
        raise DeployError(f"{name!r} is a reserved service name")
    return name


def _place(services: list[Service], dotted: list[str], name: str | None) -> None:
    name = _service_name(dotted, name)
    for module in dotted:
        if not _importable(module):
            raise DeployError(f"no module {module} (is it installed / spelled right?)")
        other = next((s.name for s in services if module in s.modules), None)
        if other is not None and other != name:
            raise DeployError(
                f"{module} is already deployed in the service {other!r}: a module "
                "runs in exactly one service. To move it, delete it from that "
                "service's SANDLOOM_MODULES (inside the generated block), rerun with "
                "--force, then move its data (skill sandloom-extract-module)"
            )
    target = next((s for s in services if s.name == name), None)
    if target is None:
        used = {s.broker_db for s in services}
        target = Service(name, [], max(used | {1}) + 1)
        services.append(target)
    target.modules += [m for m in dotted if m not in target.modules]


