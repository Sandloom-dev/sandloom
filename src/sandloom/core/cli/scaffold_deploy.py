def _sha(body: str) -> str:
    return hashlib.sha256(body.encode()).hexdigest()[:12]


def regions(text: str) -> dict[str, tuple[str, str | None]]:
    """``name -> (body, recorded sha)`` of the generated regions in ``text``."""
    return {m["name"]: (m["body"], m["sha"]) for m in _REGION.finditer(text)}


def edited(body: str, sha: str | None) -> bool:
    """A hand edit inside a generated region (an empty fresh one is not)."""
    return _sha(body) != sha if sha else bool(body.strip())


def apply_regions(
    text: str, bodies: dict[str, str], *, force: bool, where: str
) -> tuple[str, list[str]]:
    """``text`` with each named region's body replaced; the diffs of the
    regions that were edited by hand (then nothing is applied unless
    ``force``)."""
    refusals: list[str] = []
    found = regions(text)
    missing = sorted(set(bodies) - set(found))
    if missing:
        raise DeployError(
            f"{where}: no generated block(s) {missing} (the `{_BEGIN}<name>` "
            "markers): restore them, or move the file aside and run `sandloom add "
            "deploy` again to recreate it"
        )
    for name in bodies:
        body, sha = found[name]
        if edited(body, sha) and body != bodies[name]:
            diff = difflib.unified_diff(
                body.splitlines(keepends=True),
                bodies[name].splitlines(keepends=True),
                f"{where} [{name}] (edited)",
                f"{where} [{name}] (generated)",
            )
            refusals.append("".join(diff))
    if refusals and not force:
        return text, refusals

    def repl(m: re.Match[str]) -> str:
        name = m["name"]
        if name not in bodies:
            return m.group(0)
        body = bodies[name]
        return (
            f"{m['indent']}{_BEGIN}{name} sha:{_sha(body)}\n"
            f"{body}{m['indent']}{_END}{name}\n"
        )

    return _REGION.sub(repl, text), refusals


