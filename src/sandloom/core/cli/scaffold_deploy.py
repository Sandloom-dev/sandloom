@dataclass
class Service:
    name: str
    modules: list[str]
    broker_db: int
    topology: _dp.ServiceTopology = field(
        default_factory=lambda: _dp.ServiceTopology(())
    )


def read_services(text: str) -> list[Service]:
    """The generated services of a profile, in order."""
    body = regions(text).get("service-env", ("", None))[0]
    names = re.findall(r"^x-([a-z][a-z0-9_]*)-env: &", body, re.M)
    if not names:
        return []
    yaml = _yaml()
    data = yaml.safe_load(text) or {}
    out = []
    for name in names:
        env = data.get(f"x-{name}-env") or {}
        broker = re.search(r"/(\d+)$", str(env.get("BROKER_URL", "")))
        out.append(
            Service(
                name,
                _dp.modules_of({"environment": env}),
                int(broker.group(1)) if broker else 0,
            )
        )
    return out


def _yaml() -> Any:
    try:
        return importlib.import_module("yaml")
    except ImportError as exc:  # pragma: no cover - the check extra ships it
        raise DeployError(
            "sandloom add deploy needs PyYAML: install sandloom[check]"
        ) from exc


def _q(value: Any) -> str:
    """A single-quoted YAML scalar of JSON (no quote inside JSON keys)."""
    return "'" + json.dumps(value, sort_keys=True).replace("'", "''") + "'"


def _env_block(
    project: Project, svc: Service, bindings: dict[str, Any], issuer: bool
) -> list[str]:
    up = svc.name.upper()
    lines = [
        f"x-{svc.name}-env: &{svc.name}-env",
        f"{_I}<<: *common-env",
        f"{_I}SANDLOOM_MODULES: {_q(svc.modules)}",
        f"{_I}# Labels consumer ids, the subscription inventory and diagnostics.",
        f"{_I}SANDLOOM_SERVICE_NAME: {svc.name}",
        f"{_I}DATABASE_URL: postgresql+asyncpg://sandloom:sandloom@db:5432/"
        f"{project.db_prefix}_{svc.name}",
        f"{_I}BROKER_URL: redis://redis:6379/{svc.broker_db}",
    ]
    for module in svc.modules:
        lines += [f"{_I}{line}" for line in MODULE_ENV.get(module, ())]
    if issuer:
        lines += [
            f"{_I}# The token ISSUER: the only process holding the signing key",
            f"{_I}# (prefer SECRETS_DIR + a jwt_private_key file) and the",
            f"{_I}# symmetric JWT_SECRET of its emailed verification/reset tokens.",
            f"{_I}JWT_PRIVATE_KEY: ${{JWT_PRIVATE_KEY:?set JWT_PRIVATE_KEY "
            f"(sandloom keys generate) - the issuer only}}",
            f"{_I}JWT_SECRET: ${{JWT_SECRET:?set JWT_SECRET (openssl rand -hex 32) "
            f"- the issuer only}}",
        ]
    lines += [
        f"{_I}# Its RPC identity (shared by its worker/beat): an X25519 key that",
        *(
            [
                f"{_I}# authenticates every call and response, and an Ed25519 key",
                f"{_I}# that signs its commands (it calls other services).",
            ]
            if bindings
            else [f"{_I}# authenticates every call and response."]
        ),
        f"{_I}RPC_SERVICE_ID: {svc.name}",
    ]
    if bindings:
        lines += [
            f"{_I}RPC_PRIVATE_KEY: ${{{up}_RPC_PRIVATE_KEY:?set {up}_RPC_PRIVATE_KEY "
            f"(sandloom keys generate --purpose rpc --service {svc.name})}}",
            f"{_I}RPC_KEY_ID: ${{{up}_RPC_KEY_ID:?set {up}_RPC_KEY_ID}}",
        ]
    lines += [
        f"{_I}RPC_DH_PRIVATE_KEY: ${{{up}_RPC_DH_PRIVATE_KEY:?set "
        f"{up}_RPC_DH_PRIVATE_KEY (sandloom keys generate --purpose "
        f"{'rpc' if bindings else 'rpc-dh'} --service {svc.name})}}",
        f"{_I}RPC_DH_KEY_ID: ${{{up}_RPC_DH_KEY_ID:?set {up}_RPC_DH_KEY_ID}}",
        f"{_I}# Exactly the contracts its modules consume from other services"
        + ("" if issuer else "."),
        *([f"{_I}# (+ the remote token-claims contributors)."] if issuer else []),
        f"{_I}SERVICE_BINDINGS: {_q(bindings)}",
    ]
    return lines


def _service_blocks(svc: Service) -> tuple[list[str], list[str]]:
    i2, i3, i4 = _I * 2, _I * 3, _I * 4
    migrate = [
        f"{_I}migrate-{svc.name}:",
        f"{i2}<<: *migrate",
        # init-databases.sh ran only on the volume's first start: a service
        # added later creates its own database (idempotent).
        f"{i2}command: {_MIGRATE_COMMAND}",
        f"{i2}environment: *{svc.name}-env",
    ]
    http = [
        f"{_I}{svc.name}:",
        f"{i2}<<: *http-service",
        f"{i2}environment:",
        f"{i3}<<: [*{svc.name}-env, *http-env]",
        f"{i2}depends_on:",
        f"{i3}<<: *after-migrate",
        f"{i3}migrate-{svc.name}:",
        f"{i4}condition: service_completed_successfully",
    ]
    return migrate, http


def _worker_blocks(svc: Service) -> list[str]:
    """A worker for a service whose modules ship tasks, and the ONE beat of
    its own broker when they schedule periodic tasks (SANDLOOM-T010)."""
    i2, i3, i4, i5 = _I * 2, _I * 3, _I * 4, _I * 5
    out: list[str] = []
    topo = svc.topology
    if topo.tasks or topo.periodic:
        out += [
            f"{_I}{svc.name}-worker:",
            f"{i2}<<: *service-runtime",
            f"{i2}image: *image",
            f"{i2}build: *build",
            f"{i2}volumes:",
            f"{i3}- appdata:/app/data",
            f'{i2}command: ["celery", "-A", "sandloom.core.worker", "worker", '
            '"--loglevel=INFO"]',
            f"{i2}environment:",
            f"{i3}<<: [*{svc.name}-env, *worker-env]",
            f"{i3}SANDLOOM_SERVICE_NAME: {svc.name}-worker",
            f"{i3}WORKER_CONCURRENCY: ${{{svc.name.upper()}_WORKER_CONCURRENCY:-1}}",
            f"{i2}healthcheck:",
            f'{i3}test: ["CMD", "python", "-m", "sandloom.core.worker", "healthcheck"]',
            f"{i3}interval: 30s",
            f"{i3}timeout: 5s",
            f"{i3}retries: 3",
            f"{i3}start_period: 60s",
            f"{i2}depends_on:",
            f"{i3}<<: *after-migrate",
            f"{i3}migrate-{svc.name}:",
            f"{i4}condition: service_completed_successfully",
            f"{i2}restart: unless-stopped",
            f"{i2}deploy:",
            f"{i3}resources:",
            f"{i4}limits:",
            f'{i5}cpus: "0.5"',
            f"{i5}memory: 512m",
        ]
    if topo.periodic:
        out += [
            f"{_I}{svc.name}-beat:",
            f"{i2}<<: *service-runtime",
            f"{i2}image: *image",
            f"{i2}build: *build",
            f"{i2}volumes:",
            f"{i3}- appdata:/app/data",
            f'{i2}command: ["celery", "-A", "sandloom.core.worker", "beat", '
            '"--loglevel=INFO", "--schedule=/tmp/celerybeat-schedule"]',
            f"{i2}environment:",
            f"{i3}<<: *{svc.name}-env",
            f"{i3}SANDLOOM_SERVICE_NAME: {svc.name}-beat",
            f'{i3}DB_POOL_SIZE: "1"',
            f'{i3}DB_MAX_OVERFLOW: "0"',
            f'{i3}CONTRACT_DB_POOL_SIZE: "1"',
            f'{i3}CONTRACT_DB_MAX_OVERFLOW: "0"',
            f"{i2}healthcheck:",
            f"{i3}disable: true",
            f"{i2}depends_on:",
            f"{i3}redis:",
            f"{i4}condition: service_started",
            f"{i3}migrate-{svc.name}:",
            f"{i4}condition: service_completed_successfully",
            f"{i2}restart: unless-stopped",
            f"{i2}deploy:",
            f"{i3}resources:",
            f"{i4}limits:",
            f'{i5}cpus: "0.25"',
            f"{i5}memory: 256m",
        ]
    return out


def _max_connections(services: list[Service]) -> int:
    budget = _RESERVE
    for svc in services:
        budget += _CONNECTIONS["http"] + _CONNECTIONS["migrate"]
        if svc.topology.tasks or svc.topology.periodic:
            budget += _CONNECTIONS["worker"]
        if svc.topology.periodic:
            budget += _CONNECTIONS["beat"]
    return max(150, math.ceil(budget / 50) * 50)


def _blocks(lines: list[str]) -> str:
    return "".join(f"{line}\n" if line else "\n" for line in lines)


def render(
    project: Project, services: list[Service]
) -> tuple[dict[str, str], dict[str, str], list[str]]:
    """The compose and gateway region bodies, and the consumed contracts no
    service provides (warnings, SANDLOOM-T003)."""
    topologies = {s.name: s.topology for s in services}
    bindings, unresolved = _dp.expected_bindings(topologies, project.port)
    allowed = allowlist_from_bindings(bindings)
    envs: list[str] = []
    migrates: list[str] = []
    https: list[str] = []
    workers: list[str] = []
    for svc in services:
        envs += [
            *_env_block(project, svc, bindings[svc.name], svc.topology.issues_tokens),
            "",
        ]
        migrate, http = _service_blocks(svc)
        migrates += [*migrate, ""]
        https += [*http, ""]
        extra = _worker_blocks(svc)
        workers += [*extra, ""] if extra else []
    databases = " ".join(f"{project.db_prefix}_{s.name}" for s in services)
    compose = {
        "allowlist": _blocks([f"{_I}RPC_ALLOWED_CALLS: {_q(allowed)}"]),
        "service-env": _blocks(envs[:-1] if envs else []),
        "services": _blocks((migrates + https + workers)[:-1]),
        "gateway-depends": _blocks([f"{_I * 3}- {s.name}" for s in services]),
        "database": _blocks(
            [
                f'{_I * 2}command: ["postgres", "-c", '
                f'"max_connections={_max_connections(services)}"]',
                f"{_I * 2}environment:",
                f"{_I * 3}POSTGRES_DB: sandloom",
                f"{_I * 3}POSTGRES_USER: sandloom",
                f"{_I * 3}POSTGRES_PASSWORD: sandloom",
                f"{_I * 3}POSTGRES_MULTIPLE_DATABASES: {databases}",
            ]
        ),
    }
    prefixes, conflicts = _dp.gateway_prefixes(
        {s.name: s.topology.routes for s in services}
    )
    if conflicts:
        raise DeployError(
            "two services serve the same route prefix, which a gateway cannot "
            f"split: {'; '.join(conflicts)}. Deploy those modules together, or "
            "give them distinct route prefixes (SANDLOOM-T014)"
        )
    matchers = _dp.route_matchers({s.name: s.topology.routes for s in services})
    upstreams: list[str] = []
    routes: list[str] = []
    for svc in services:
        upstreams += [
            f"    upstream {svc.name} {{",
            f"        zone upstream_{svc.name} 64k;",
            f"        server {svc.name}:{project.port} resolve;",
            "        keepalive 32;",
            "        keepalive_timeout 60s;",
            "    }",
        ]
        routes.append(f"        # {svc.name}: {', '.join(svc.modules)}")
        routes += [
            line
            for prefix in prefixes[svc.name]
            if prefix != _dp.CATCH_ALL
            and not prefix.startswith(("/_sandloom", "/diagnostics", "/metrics"))
            for line in _locations(prefix, svc.name, matchers)
        ]
    catch_all = [s.name for s in services if _dp.CATCH_ALL in prefixes[s.name]]
    gateway = {
        "upstreams": _blocks(upstreams),
        "routes": _blocks(routes + _fallback(catch_all[0] if catch_all else None)),
    }
    return compose, gateway, unresolved


def _locations(prefix: str, upstream: str, matchers: list[Any]) -> list[str]:
    """The nginx locations of one route prefix, bounded at its segment the
    way Starlette matches a route: everything below ``/shop/``, and
    ``/shop`` itself (exact) -- never ``/shopping``, which an unbounded
    ``location /shop`` would steal from the catch-all's ``/{slug}``.

    The bare prefix goes to the service whose routes match it (``/auth``
    with only ``/auth/...`` routes is the catch-all's ``/{slug}``), else to
    the prefix's own service; the exact location also keeps nginx from
    redirecting it to ``/shop/``."""
    if prefix == _dp.EXACT_ROOT:
        return [f"        location = / {{ proxy_pass http://{upstream}; }}"]
    owner = _dp.route_owner(prefix, matchers)
    exact = owner[0] if owner is not None else upstream
    return [
        f"        location = {prefix} {{ proxy_pass http://{exact}; }}",
        f"        location {prefix}/ {{ proxy_pass http://{upstream}; }}",
    ]


def _fallback(owner: str | None) -> list[str]:
    """The catch-all ``location /``: the edge's 404, or the service serving
    root-level parameter routes (``/{slug}``), the internal surfaces (``/_sandloom``,
    ``/diagnostics``, ``/metrics``, ``/contracts``, a service's ``/health/...``
    and ``/ready``, docs) then answering 404 explicitly."""
    if owner is None:
        return [
            "        # internal surfaces and unknown paths: 404 at the edge",
            "        location / { return 404; }",
        ]
    lines = [f"        # every other path: {owner} serves root-level routes"]
    for root in _dp.INTERNAL_ROOTS:
        if root != "health":  # `= /health` is the gateway's own probe
            lines.append(f"        location = /{root} {{ return 404; }}")
        lines.append(f"        location /{root}/ {{ return 404; }}")
    return [*lines, f"        location / {{ proxy_pass http://{owner}; }}"]


