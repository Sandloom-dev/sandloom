def service_of(compose_path: Path, dotted: str) -> str | None:
    """The microservices-profile service that serves module ``dotted``."""
    compose = _dp.load_profile(compose_path)
    return next(
        (name for name, mods in _dp.http_services(compose).items() if dotted in mods),
        None,
    )


def refresh(project: Project) -> Result:
    """Re-derive every generated block (``sandloom add deploy --refresh``)."""
    return deploy(project)


