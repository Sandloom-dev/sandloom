def check(project: Project, env_file: Path | None = None) -> int:
    """``sandloom add deploy --check``: the split invariants (SANDLOOM-T014), then each
    HTTP service booted alone with exactly its environment (``sandloom doctor``'s
    settings, startup preflight, composition root and bound contracts; no
    network). Keys: ``env_file`` (a compose ``--env-file``), else fresh
    in-memory development keys."""
    compose_path = project.deploy_dir / PROFILE
    if not compose_path.is_file():
        print(f"error: no {compose_path}", file=sys.stderr)
        return 1
    report = _dp.profile_problems(project.deploy_dir)
    for line in report.warnings:
        print(f"warning: {line}")
    for line in report.problems:
        print(f"error: {line}")
    text = compose_path.read_text(encoding="utf-8")
    shell = (
        _dp.parse_env_file(env_file.read_text(encoding="utf-8"))
        if env_file is not None
        else _dp.dev_shell(text)
    )
    booted = _dp.boot_problems(project.deploy_dir, shell, pythonpath=str(project.root))
    for name, failures in booted.items():
        print(f"boot {name}: {'OK' if not failures else 'FAILED'}")
        for failure in failures:
            print(f"  {failure}")
    failed = bool(report.problems) or any(booted.values())
    print(
        "split check: "
        + ("FAILED (sandloom explain SANDLOOM-T014)" if failed else "OK")
    )
    return 1 if failed else 0


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="sandloom add deploy",
        description=(
            "Split the application into services: create or update the "
            "microservices profile and its gateway (configuration only)"
        ),
    )
    parser.add_argument(
        "modules",
        nargs="*",
        help="modules to put in the service: short names (the project's "
        "module, else a bundled one: identity, tenancy, billing) or dotted",
    )
    parser.add_argument(
        "--service", default=None, help="the service (default: the module's name)"
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--refresh",
        action="store_true",
        help="re-derive every generated block (bindings, routes, workers)",
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="check the profile (SANDLOOM-T014) and boot every service alone",
    )
    parser.add_argument(
        "--env-file",
        type=Path,
        default=None,
        help="--check: the keys (default: fresh in-memory development keys)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite hand edits inside the generated blocks",
    )
    parser.add_argument(
        "--deploy-dir", type=Path, default=None, help="the deploy/ directory"
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    if bool(args.modules) == (args.refresh or args.check):
        parser.error("name the module(s) to deploy, or pass --refresh / --check")
    try:
        project = Project.find(Path.cwd(), args.deploy_dir)
        if args.check:
            return check(project, args.env_file)
        result = deploy(project, args.modules or None, args.service, force=args.force)
    except (DeployError, OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if result.refusals and not args.force:
        print(
            "error: generated blocks were edited by hand; nothing written. Move "
            "the edit outside the markers (or into a compose override file), or "
            "rerun with --force to overwrite it:\n",
            file=sys.stderr,
        )
        for diff in result.refusals:
            print(diff, file=sys.stderr)
        return 1
    _report(project, result)
    return 0


def _report(project: Project, result: Result) -> None:
    for path in result.created:
        print(f"created {path}")
    for path in result.written:
        print(f"updated {path}")
    if not result.created and not result.written:
        print("the profile is up to date (nothing changed)")
    print("\nservices:")
    for svc in result.services:
        extra = " + worker" if svc.topology.tasks or svc.topology.periodic else ""
        extra += " + beat" if svc.topology.periodic else ""
        print(f"  {svc.name:<12} {', '.join(svc.modules)}{extra}")
    for item in result.unresolved:
        service, contract = item.split(": ", 1)
        print(
            f"warning: {service} consumes {contract}, which no deployed service "
            "provides: deploy its module (SANDLOOM-T003)",
            file=sys.stderr,
        )
    rel = _relpath(project.deploy_dir, Path.cwd())
    print(
        "\nNext:\n"
        "  uv run sandloom add deploy --check       # invariants + every service "
        "boots alone\n"
        f"  uv run sandloom keys dev-env --out {rel}/.env.microservices   "
        "# DEV-ONLY keys\n"
        f"  docker compose --env-file {rel}/.env.microservices -f {rel}/{PROFILE} "
        "up --build\n"
        "`uv run sandloom test` checks the profile too "
        "(schema & deploy, SANDLOOM-T014). "
        "Production keys: `sandloom keys generate` (each variable the profile "
        "requires names its command)."
    )


