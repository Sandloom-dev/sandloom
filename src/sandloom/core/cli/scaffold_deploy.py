"""``sandloom add deploy`` — split an application into services, by configuration.

    sandloom add deploy <module> [<module> ...] --service <name>
    sandloom add deploy --refresh
    sandloom add deploy --check [--env-file deploy/.env.microservices]

The first run creates the microservices profile from the templates shipped in
the package (``sandloom/core/cli/templates/deploy``): ``deploy/docker-compose.
microservices.yml`` (the shared env anchor, the durable Streams bus, Redis,
one Postgres server with a database per service), ``deploy/gateway/nginx.conf``
and ``deploy/postgres/init-databases.sh``. Every run then puts the modules in
the service (a new one, or an existing one: incremental) and re-derives
everything the split depends on from what each service's modules provide and
consume (registration only, no I/O):

* per service: an env anchor (its ``SANDLOOM_MODULES``, database, broker, RPC
  identity and keys, issuer-only signing material when it issues tokens),
  a ``migrate-<service>`` one-shot (it creates the service's database when
  missing: ``init-databases.sh`` runs only on an empty volume), the HTTP
  service after it, a worker when its modules ship ``tasks.py`` and the ONE
  beat of its broker when they schedule periodic tasks (SANDLOOM-T010);
* ``SERVICE_BINDINGS``: exactly the contracts each service consumes from
  another one, plus ``<module>.claims.v1`` of every remote claims contributor
  on the token issuer; ``RPC_ALLOWED_CALLS`` derived from them;
* the databases (``POSTGRES_MULTIPLE_DATABASES``, a ``max_connections`` that
  fits the stack's connection budget) and the gateway's ``depends_on``;
* an nginx upstream per service and a ``location`` per route prefix of its
  modules (never ``/_sandloom``, ``/diagnostics`` or ``/metrics``); a service with
  root-level routes gets ``location = /`` (``/``) or the catch-all
  ``location /`` (``/{slug}``), the internal surfaces then answering 404
  explicitly; otherwise the catch-all is the edge's 404. Two services
  claiming the same route prefix, ``/`` or the root-level parameter paths are
  refused (SANDLOOM-T014).

What it writes lives between ``# >>> generated by sandloom add deploy: <block>``
markers. Everything outside them is the user's and is kept; an edit inside
one makes the run refuse with a diff (``--force`` overwrites it). The same
modules and service again change nothing. ``--refresh`` re-derives every block
after a code change (a newly consumed contract, a new route prefix).

``--check`` runs the split invariants ``sandloom test`` runs (SANDLOOM-T014), then
boots every service alone with exactly its environment (as ``sandloom doctor``
boots a process: settings, startup preflight, composition root, every
consumed contract bound; no network).

Keys: ``sandloom keys dev-env`` writes a development-only env file with fresh keys
for every service; production generates them with ``sandloom keys generate`` (the
profile names the command for every variable it requires).
"""

