@dataclass(frozen=True)
class Project:
    """Where the profile goes and how the application's image runs."""

    root: Path
    deploy_dir: Path
    modules_package: str
    title: str
    build_context: str
    image: str
    port: int
    db_prefix: str
    app_env: tuple[tuple[str, str], ...] = ()
    #: The framework checkout (its standard modules are top-level packages).
    framework: bool = False

    @classmethod
    def find(cls, start: Path, deploy_dir: Path | None = None) -> Project:
        root = next(
            (
                p
                for p in (start, *start.parents)
                if (p / "architecture_rules.yml").is_file()
            ),
            None,
        )
        if root is None:
            raise DeployError(
                "no architecture_rules.yml here or above: run `sandloom add deploy` "
                "from the project root (an `sandloom new` app, or the framework's "
                "backend/)"
            )
        rules = load_rules(root / "architecture_rules.yml")
        package = rules.modules_package
        if deploy_dir is None:
            # The project's deploy/ (an app's), else the one next to it (the
            # framework's backend/ -> ../deploy), else a new deploy/.
            deploy_dir = next(
                (
                    d / "deploy"
                    for d in (root, root.parent)
                    if any((d / "deploy" / "compose").glob("*.yml"))
                ),
                root / "deploy",
            )
        framework = rules.is_framework_tree
        top = "sandloom" if framework else package.split(".")[0]
        dockerfile = root / ("deploy/docker/Dockerfile" if framework else "Dockerfile")
        expose = re.search(
            r"^EXPOSE\s+(\d+)",
            dockerfile.read_text(encoding="utf-8") if dockerfile.is_file() else "",
            re.M,
        )
        app_env: list[tuple[str, str]] = []
        if not framework:
            app_env.append(
                ("CONTRACT_DTO_PACKAGES", f"'{json.dumps([rules.shared_dto_package])}'")
            )
            if (root / top / "asgi.py").is_file():
                app_env.append(("SANDLOOM_COMPOSITION_ROOT", f"{top}.asgi"))
        context = Path(_relpath(root, deploy_dir / "compose"))
        return cls(
            root=root,
            deploy_dir=deploy_dir,
            modules_package=package,
            title="Sandloom" if framework else top,
            build_context=str(context),
            image="sandloom:local" if framework else f"{top}:local",
            port=int(expose.group(1)) if expose else 8000,
            db_prefix="sandloom" if framework else top,
            app_env=tuple(app_env),
            framework=framework,
        )

    def dotted(self, module: str) -> str:
        """``notes`` -> ``<modules_package>.notes``; an installed module
        package's entry-point name (``identity``) -> its import path
        (``sandloom_identity``); a dotted or top-level import path stays."""
        if "." in module:
            return module
        if self.modules_package:
            own = f"{self.modules_package}.{module}"
            if _importable(own):
                return own
        installed = {m.name: m.path for m in installed_modules()}
        return installed.get(module, module)


def _relpath(target: Path, start: Path) -> str:
    return os.path.relpath(target.resolve(), start.resolve())


def _importable(module: str) -> bool:
    try:
        return importlib.util.find_spec(module) is not None
    except (ImportError, ValueError):
        return False


