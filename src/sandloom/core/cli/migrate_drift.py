"""``sandloom migrate drift`` — models against the chain heads (SANDLOOM-T006, spec
§5.6).

A module's models and its migration chain must agree: a model change without
its revision ships a schema the code does not expect. The check:

1. creates a scratch database next to the default one (same server, a
   ``<name>_drift_<hex>`` database; dropped at the end);
2. applies the core chain, then each module's own chain to its head, in the
   dependency order ``upgrade-all`` uses;
3. runs Alembic's autogenerate comparison (``alembic check``) of each
   module's chain against the scratch database: its ``env.py`` compares
   ONLY the module's tables.

Any difference fails with the module, the operations autogenerate found and
the fix (``sandloom migrate new <module> "<message>"``). A module with no chain is
skipped; a non-PostgreSQL default database skips the check (said so).

Nothing touches the configured databases: the scratch database is the only
one written.
"""

from __future__ import annotations

import uuid
from collections.abc import Iterator, Sequence
from contextlib import contextmanager
from dataclasses import dataclass

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine
from sqlalchemy.engine import make_url

from sandloom.core.descriptors import ModuleDescriptor
from sandloom.core.migrations.migrations import (
    _order_by_dependencies,
    build_plan,
    resolve_database_sync_url,
    run_core_upgrade,
    version_table_for,
)

#: The catalogue code of a drift (``sandloom explain SANDLOOM-T006``).
CODE = "SANDLOOM-T006"


@dataclass(frozen=True)
class Drift:
    """One module whose models differ from its chain head."""

    module: str
    detail: str

    def describe(self) -> str:
        return (
            f"{self.module}: models differ from the migration chain head "
            f"[{CODE}]\n    {self.detail}\n"
            f'    fix: sandloom migrate new {self.module} "<message>" (then review '
            "the revision)"
        )


@contextmanager
def scratch_database(base_sync_url: str) -> Iterator[str]:
    """A fresh database on the server of ``base_sync_url``; dropped on exit."""
    base = make_url(base_sync_url)
    name = f"{base.database}_drift_{uuid.uuid4().hex[:8]}"
    admin = create_engine(base, isolation_level="AUTOCOMMIT")
    try:
        with admin.connect() as conn:
            conn.exec_driver_sql(f'CREATE DATABASE "{name}"')
        try:
            yield base.set(database=name).render_as_string(hide_password=False)
        finally:
            with admin.connect() as conn:
                conn.exec_driver_sql(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
    finally:
        admin.dispose()


def _chain_config(descriptor: ModuleDescriptor, url: str) -> Config:
    cfg = Config()
    cfg.set_main_option("script_location", str(descriptor.migrations_path))
    cfg.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    cfg.set_main_option("version_table", version_table_for(descriptor))
    return cfg


def _ordered(descriptors: Sequence[ModuleDescriptor]) -> list[ModuleDescriptor]:
    by_name = {d.name: d for d in descriptors}
    valid = {e.module for e in build_plan(descriptors).entries if e.valid}
    return [by_name[n] for n in _order_by_dependencies(by_name, valid) if n in by_name]


@contextmanager
def chains_at_head(descriptors: Sequence[ModuleDescriptor]) -> Iterator[str]:
    """A scratch database with the core chain and every module chain at
    head (dependency order); its sync URL, dropped on exit."""
    with scratch_database(resolve_database_sync_url("default")) as url:
        run_core_upgrade(head="head", dry_run=False, database_url=url)
        for descriptor in _ordered(descriptors):
            command.upgrade(_chain_config(descriptor, url), "head")
        yield url


def find_drift(descriptors: Sequence[ModuleDescriptor]) -> list[Drift]:
    """The modules whose models differ from their chain head (empty: none)."""
    modules = _ordered(descriptors)
    if not modules:
        return []
    with chains_at_head(modules) as url:
        drifts: list[Drift] = []
        for descriptor in modules:
            try:
                command.check(_chain_config(descriptor, url))
            except AutogenerateDiffsDetected as exc:
                drifts.append(Drift(descriptor.name, str(exc).strip()))
        return drifts


def drift_supported() -> str | None:
    """Why the drift check cannot run here (``None``: it can)."""
    backend = make_url(resolve_database_sync_url("default")).get_backend_name()
    if backend != "postgresql":
        return f"the default database is {backend}, not PostgreSQL"
    return None


def run(descriptors: Sequence[ModuleDescriptor]) -> int:
    """``sandloom migrate drift``: print each drift; exit 1 on any."""
    reason = drift_supported()
    if reason is not None:
        print(f"migration drift: skipped ({reason})")
        return 0
    drifts = find_drift(descriptors)
    for drift in drifts:
        print(drift.describe())
    checked = len(_ordered(descriptors))
    if drifts:
        print(f"migration drift: {len(drifts)} of {checked} module chain(s) [{CODE}]")
        return 1
    print(f"migration drift: none ({checked} module chain(s) at their models)")
    return 0


