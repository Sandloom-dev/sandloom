"""I-19: a module boots ALONE through ``create_app`` + lifespan.

``test_module_subset`` pins the loader; booting the real application (every
startup check, route validation and startup task) with one module in
``SANDLOOM_MODULES`` catches the boot-time coupling static import rules cannot see.
Each module pins its own boot in its tests (``tests/test_module_wiring.py``,
generated by ``sandloom add``; the bundled modules carry the same file). This
file proves the gate itself: the only accepted refusal is the documented
``ContractBindingError`` for required consumed contracts.
"""

from __future__ import annotations

import pytest

from sandloom.core.testing import ModuleBootError, boot_module_alone

# --- positive detection: the gate catches boot-time coupling --------------

_PROBES = {
    # Declares a REQUIRED contract nobody provides: the documented refusal.
    "bootprobe_consumer": """
from sandloom.core.descriptors import ContractRequirement
from sandloom.core.module_api import define_module

register = define_module(
    __name__,
    version="0.1.0",
    consumes=[ContractRequirement("nobody.read.v1", reason="probe")],
)
""",
    # Calls a sibling's contract at startup without degrading: logs an error.
    "bootprobe_startup": """
from sandloom.core.module_api import define_module


def _setup(core):
    async def warm():
        core.get_service("tenancy.membership.v1")

    core.add_startup_task(warm)


register = define_module(__name__, version="0.1.0", setup=_setup)
""",
    # Resolves a sibling's contract while registering: the loader refuses.
    "bootprobe_eager": """
from sandloom.core.module_api import define_module


def _setup(core):
    core.get_service("tenancy.membership.v1").get_role


register = define_module(__name__, version="0.1.0", setup=_setup)
""",
}


@pytest.fixture
def probes(tmp_path, monkeypatch: pytest.MonkeyPatch) -> None:
    for name, source in _PROBES.items():
        (tmp_path / name).mkdir()
        (tmp_path / name / "__init__.py").write_text(source)
    monkeypatch.syspath_prepend(str(tmp_path))


async def test_required_missing_contract_is_the_explicit_refusal(probes) -> None:
    outcome = await boot_module_alone("bootprobe_consumer")
    assert not outcome.started
    assert outcome.missing_contracts == {"nobody.read.v1"}


async def test_startup_coupling_fails_the_boot(probes) -> None:
    with pytest.raises(ModuleBootError, match="bootprobe_startup"):
        await boot_module_alone("bootprobe_startup")


async def test_registration_coupling_fails_the_boot(probes) -> None:
    with pytest.raises(Exception) as excinfo:  # any refusal
        await boot_module_alone("bootprobe_eager")
    assert not isinstance(excinfo.value, ModuleBootError)
    assert "bootprobe_eager" in str(excinfo.value), excinfo.value
