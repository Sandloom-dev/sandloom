"""``sandloom docs`` and the generated reference blocks (spec §2.5; C-SDK-01/02).

``sandloom docs <name>`` prints a public name's home, tier, signature and
documentation without opening the kernel (``sandloom docs module_router``,
``sandloom docs sandloom.sdk.web``). Every public ``sandloom.sdk`` module starts with a
generated reference block — its beginner and advanced names and its doc
page — kept current by ``sandloom docs --write`` and checked by ``sandloom test``
(the public-API gate, SANDLOOM-T008).
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import pkgutil
import re
import textwrap
from pathlib import Path
from types import ModuleType
from typing import Annotated, Any, get_args, get_origin

from sandloom.sdk._prim.docs_wire import describe_wire
from sandloom.sdk._prim.recipes import _recipe, _recipe_index

#: The markers of a module's generated reference block.
BEGIN = ".. sandloom-reference (generated by `sandloom docs --write`; do not edit)"
END = ".. end sandloom-reference"
_BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
_WIDTH = 79


def public_modules(*, installed_only: bool = False) -> list[ModuleType]:
    """``sandloom.sdk`` and its public submodules (no ``_`` segment), sorted.

    ``installed_only`` skips a module whose optional dependency is missing
    (``sandloom.sdk.testing`` needs pytest, which a production install lacks), so
    a name lookup works there; writing or checking the reference never skips.
    """
    root = importlib.import_module("sandloom.sdk")
    found = sorted(
        info.name
        for info in pkgutil.walk_packages(root.__path__, prefix="sandloom.sdk.")
        if not any(part.startswith("_") for part in info.name.split("."))
    )
    names = ["sandloom.sdk", *found]
    modules: list[ModuleType] = []
    for name in names:
        try:
            modules.append(importlib.import_module(name))
        except ModuleNotFoundError as exc:
            if not installed_only or (exc.name or "").startswith("sandloom"):
                raise
            _UNAVAILABLE[name] = exc.name or "?"
    return modules


#: Public modules skipped for a missing optional dependency (name -> import).
_UNAVAILABLE: dict[str, str] = {}

#: The ``sandloom`` extra that brings an optional dependency.
_EXTRA_OF = {"pytest": "testing", "pytest_asyncio": "testing", "celery": "celery"}


def doc_page(module: str) -> str:
    """The reference page of a public module."""
    tail = module.removeprefix("sandloom.sdk").lstrip(".").replace(".", "/") or "index"
    return f"docs/reference/sdk/{tail}.md"


def reference_block(module: ModuleType) -> str:
    """The generated reference block of ``module`` (names by tier, doc page)."""
    names = list(getattr(module, "__all__", ()))
    beginner = [n for n in getattr(module, "__beginner__", ()) if n in names]
    advanced = [n for n in names if n not in beginner]

    def wrap(label: str, items: list[str]) -> list[str]:
        text = ", ".join(sorted(items)) or "-"
        return textwrap.wrap(f"{label}: {text}", width=_WIDTH, subsequent_indent="    ")

    lines = [BEGIN]
    lines += wrap("beginner", beginner)
    lines += wrap("advanced", advanced)
    lines.append(f"docs: {doc_page(module.__name__)}; signatures: sandloom docs <name>")
    lines.append(END)
    return "\n".join(lines) + "\n"


def _source(module: ModuleType) -> Path:
    file = getattr(module, "__file__", None)
    if not file:
        raise RuntimeError(f"{module.__name__} has no source file")
    return Path(file)


def render_with_block(module: ModuleType) -> str:
    """``module``'s source with its reference block current.

    The block sits at the end of the module docstring (added when absent).
    """
    source = _source(module).read_text(encoding="utf-8")
    block = reference_block(module)
    if _BLOCK.search(source):
        return _BLOCK.sub(lambda _m: block, source, count=1)
    match = re.match(r'(\s*""")(.*?)(""")', source, re.S)
    if match is None:
        return f'"""{module.__name__}.\n\n{block}"""\n\n{source}'
    body = match.group(2).rstrip("\n")
    return source[: match.start(2)] + body + "\n\n" + block + source[match.end(2) :]


def stale_blocks() -> list[str]:
    """The public modules whose reference block is missing or out of date."""
    return [
        m.__name__
        for m in public_modules()
        if render_with_block(m) != _source(m).read_text(encoding="utf-8")
    ]


def write_blocks() -> list[str]:
    """Rewrite the stale reference blocks; returns the modules written."""
    written = []
    for module in public_modules():
        text = render_with_block(module)
        path = _source(module)
        if text != path.read_text(encoding="utf-8"):
            path.write_text(text, encoding="utf-8")
            written.append(module.__name__)
    return written


def _find(name: str) -> list[tuple[str, Any, ModuleType]]:
    """``(home, object, module)`` for a name or a dotted path."""
    modules = public_modules(installed_only=True)
    if any(m.__name__ == name for m in modules):
        module = next(m for m in modules if m.__name__ == name)
        return [(name, module, module)]
    short = name.rsplit(".", 1)[-1]
    return [
        (f"{module.__name__}.{short}", getattr(module, short), module)
        for module in modules
        if short in getattr(module, "__all__", ())
        and ("." not in name or name.startswith(module.__name__ + "."))
    ]


def describe(name: str) -> str:
    """The ``sandloom docs <name>`` text."""
    found = _find(name)
    if not found:
        missing = next(
            (
                dep
                for mod, dep in _UNAVAILABLE.items()
                if name in (mod, mod.rsplit(".", 1)[-1])
            ),
            None,
        )
        if missing is not None:
            extra = _EXTRA_OF.get(missing.split(".")[0], "testing")
            return (
                f"sandloom docs: {name!r} needs {missing!r}, which is not "
                f'installed: pip install "sandloom[{extra}]"'
            )
        return f"sandloom docs: no public sandloom.sdk name {name!r}"
    out = []
    for home, obj, module in found:
        if isinstance(obj, ModuleType):
            out.append(f"{home} (module) — {doc_page(home)}")
            out.append(reference_block(obj))
            continue
        tier = (
            "beginner"
            if home.rsplit(".", 1)[-1] in getattr(module, "__beginner__", ())
            else "advanced"
        )
        if get_origin(obj) is Annotated:  # a type: ``x: Mapped[CreatedAt]``
            signature = f" = Annotated[{get_args(obj)[0].__name__}, ...] (a type)"
        else:
            try:
                signature = str(inspect.signature(obj))
            except (TypeError, ValueError):
                signature = ""
        doc = inspect.getdoc(obj) or "(no documentation)"
        out.append(
            f"{home}{signature}\n  tier: {tier}; docs: {doc_page(module.__name__)}"
        )
        out.append(textwrap.indent(doc, "  "))
    return "\n".join(out)


def docs_main(argv: list[str] | None = None) -> int:
    """``sandloom docs <name> | --write | --check``."""
    parser = argparse.ArgumentParser(
        prog="sandloom docs", description="Public API 1.0 reference (sandloom.sdk)"
    )
    parser.add_argument(
        "name",
        nargs="?",
        help="a public name or module, a contract (billing.credits.v1), an event "
        "channel, `contracts`, `events`, `recipes`, or `recipe`",
    )
    parser.add_argument("topic", nargs="?", help="with `recipe`: the recipe name")
    parser.add_argument("--write", action="store_true", help="refresh the blocks")
    parser.add_argument("--check", action="store_true", help="fail on a stale block")
    args = parser.parse_args(argv)
    if args.write:
        for written in write_blocks():
            print(f"wrote the reference block of {written}")
        return 0
    if args.check:
        stale = stale_blocks()
        for name in stale:
            print(f"{name}: reference block out of date (sandloom docs --write)")
        return 1 if stale else 0
    if not args.name:
        for module in public_modules(installed_only=True):
            print(f"{module.__name__:28} {doc_page(module.__name__)}")
        return 0
    if args.name == "recipes" or (args.name == "recipe" and not args.topic):
        print(_recipe_index())
        return 0
    if args.name == "recipe":
        found = _recipe(args.topic)
        if found is None:
            print(f"sandloom docs: no recipe {args.topic!r}\n\n{_recipe_index()}")
            return 1
        print(found)
        return 0
    return _describe_any(args.name)


def _describe_any(name: str) -> int:
    """A public name, else a contract stub or an event channel (or their
    listings, ``contracts`` / ``events``)."""
    text = None if name in ("contracts", "events") else describe(name)
    if text is None or text.startswith("sandloom docs: no public"):
        wire = describe_wire(name)
        if wire is not None:
            print(wire)
            return 0
    text = (text or "") + (
        "\n  (nor a contract or event channel: sandloom docs contracts, "
        "sandloom docs events; how-tos: sandloom docs recipes)"
        if text and text.startswith("sandloom docs: no public")
        else ""
    )
    print(text)
    return 1 if text.startswith("sandloom docs: no public") else 0


__all__ = ["docs_main"]
