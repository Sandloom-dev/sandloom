"""pytest plugin of the 1.0 testing kit: the harness plus ``published`` and
``Contract`` resolution.

Activate it once per application (``sandloom new`` does)::

    [tool.pytest.ini_options]
    addopts = ["-p", "sandloom.sdk.testing.plugin"]

It is the framework harness (every fixture: ``client``, ``db``,
``real_uow_client``, ...; the test environment; the isolation guards) plus,
for every test:

- ``published(E)`` records the events the code under test publishes;
- ``Contract(REF)`` resolves through the test application's contracts
  whenever the test uses the application (any fixture built on ``sandloom_app``);
  ``fake_contract`` overrides one for a block;
- with ``SANDLOOM_TEST_OBSERVE_EFFECTS=1`` (``sandloom test`` outside ``--ci``), the
  money / security effects each route ran are recorded for ``sandloom routes
  snapshot --write`` (informational ``observed_effects``).

Activate this plugin or ``sandloom.core.testing.plugin``, not both.

.. sandloom-reference (generated by `sandloom docs --write`; do not edit)
beginner: client
advanced: ambient_uow, async_client, db, db_engine, db_uow, make_headers,
    real_uow_client, revoked_tokens, saga_harness, sandloom_app,
    sandloom_cache, sandloom_core, sandloom_test_env, scratch_database,
    test_db, test_engine, user_headers
docs: docs/reference/sdk/testing/plugin.md; signatures: sandloom docs <name>
.. end sandloom-reference
"""

